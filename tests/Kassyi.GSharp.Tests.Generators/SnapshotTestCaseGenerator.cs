using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;

namespace Kassyi.GSharp.Tests.Generators;

[Generator]
public class SnapshotTestCaseGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var projectDirProvider = context.AnalyzerConfigOptionsProvider.Select((options, _) =>
            {
                options.GlobalOptions.TryGetValue("build_property.MSBuildProjectDirectory", out var projDir);
                return projDir ?? "";
            });

            context.RegisterSourceOutput(projectDirProvider, (spc, projDir) =>
            {
                if (string.IsNullOrEmpty(projDir)) return;

                var dir = new DirectoryInfo(projDir);
                string rootDir = null;
                while (dir != null)
                {
                    if (Directory.Exists(Path.Combine(dir.FullName, ".git")))
                    {
                        rootDir = dir.FullName;
                        break;
                    }

                    dir = dir.Parent;
                }

                if (rootDir == null) return;

                var searchDirs = new[]
                {
                    Path.Combine(rootDir, "src"),
                    Path.Combine(rootDir, "tests")
                };

                var testCases = new List<string>();

                foreach (var searchDir in searchDirs)
                {
                    if (!Directory.Exists(searchDir)) continue;
                    var allFiles = Directory.GetFiles(searchDir, "*.cu.cs", SearchOption.AllDirectories);

                    foreach (var file in allFiles)
                    {
                        if (file.Contains("\\bin\\") || file.Contains("\\obj\\") || file.Contains("/bin/") ||
                            file.Contains("/obj/")) continue;

                        var text = File.ReadAllText(file);
                        if (!text.Contains("GpuKernel") && !text.Contains("CudaImport")) continue;
                        if (text.Contains("[Fact]") || text.Contains("[Theory]") ||
                            text.Contains("[SkippableTheory]")) continue;

                        bool hasSkip = Regex.IsMatch(text,
                            @"\[\s*(Kassyi\.GSharp\.Core\.)?SkipSnapshotConsistency.*?\]");

                        if (!hasSkip)
                        {
                            var relativePath = file.Substring(rootDir.Length).TrimStart('\\', '/').Replace('\\', '/');
                            testCases.Add(relativePath);
                        }
                    }
                }

                testCases = testCases.Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(x => x).ToList();

                string source = @"// <auto-generated/>
using System;
using System.Collections.Generic;
using Xunit;

namespace Kassyi.GSharp.Tests
{
public static class SnapshotTestCaseSource
{
public static TheoryData<string> GetTestCases()
{
            var data = new TheoryData<string>();
";
                foreach (var tc in testCases)
                {
                    source += $"data.Add(\"{tc}\");\n";
                }

                source += @"return data;
}
}
}
";
                spc.AddSource("SnapshotTestCaseSource.g.cs", source);
            });
        }
    }
