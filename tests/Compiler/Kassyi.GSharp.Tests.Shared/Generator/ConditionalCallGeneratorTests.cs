using Kassyi.GSharp.Tests.Shared.Helpers;

namespace Kassyi.GSharp.Tests.Shared.Generator;

/// <summary>
/// The generated managed files decide <c>[Conditional]</c> again, with the parse options of the compilation and none of
/// the directives of the user's files: they leave out the calls that C# removes and <c>#define</c> the symbols that only a
/// user's file defines, before the first token, and still compile.
/// </summary>
[Category(TestCategory.Compiler)]
[TestTarget(ExecutionTarget.CpuExecution)]
public class ConditionalCallGeneratorTests
{
    private static readonly CSharpParseOptions s_parseOptions = new(LanguageVersion.Preview);

    private static readonly Lazy<(GeneratorRunResult Result, Compilation Output)> s_run = new(Run);

    private static (GeneratorRunResult Result, Compilation Output) Run()
    {
        var compilation = CSharpCompilation.Create("ConditionalCallTest")
            .WithOptions(new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true))
            .AddReferences(RoslynTestUtility.BaseReferences)
            .AddSyntaxTrees(
                Parse("Generators/ConditionalCallDefines.cs", "defines.cs"),
                Parse("Generators/ConditionalCallIterators.cs", "iterators.cs"));
        var driver = CSharpGeneratorDriver.Create(
                generators: [new GpuKernelGenerator().AsSourceGenerator()],
                additionalTexts: null,
                parseOptions: s_parseOptions,
                optionsProvider: new TestAnalyzerConfigOptionsProvider("Cpu"))
            .RunGeneratorsAndUpdateCompilation(compilation, out var output, out _);
        return (driver.GetRunResult().Results.Single(), output);
    }

    private static SyntaxTree Parse(string testCase, string path) =>
        CSharpSyntaxTree.ParseText(RoslynTestUtility.ReadTestCase(testCase), s_parseOptions, path: path);

    private static string GetSource(string hintNameSuffix)
    {
        var sources = s_run.Value.Result.GeneratedSources;
        var matches = sources.Where(s => s.HintName.EndsWith(hintNameSuffix, StringComparison.Ordinal)).ToList();
        Assert.True(matches.Count == 1, string.Join(", ", sources.Select(static s => s.HintName)));
        return matches[0].SourceText.ToString();
    }

    [Fact]
    [Scenario(TestScenario.HappyPath)]
    public void GeneratedFiles_WithDefines_Compile()
    {
        Assert.Null(s_run.Value.Result.Exception);
        var errors = s_run.Value.Output.GetDiagnostics()
            .Where(static d => d.Severity == DiagnosticSeverity.Error)
            .Select(static d => d.ToString())
            .ToList();

        Assert.True(errors.Count == 0, string.Join(Environment.NewLine, errors));
    }

    [Theory]
    [Scenario(TestScenario.Boundary)]
    [InlineData("ConditionalCallCase__DefineKernels.g.cs")]
    [InlineData("ConditionalCallCase__CallOps.DeviceStateMachines.g.cs")]
    public void GeneratedFile_FileDefinedSymbol_IsDefinedBeforeTheFirstToken(string hintName)
    {
        var lines = GetSource(hintName).Split('\n');

        Assert.Equal("// <auto-generated/>", lines[0].TrimEnd('\r'));
        Assert.Equal("#define CONDITIONAL_FILE_ON", lines[1].TrimEnd('\r'));
        Assert.Equal("#nullable enable annotations", lines[2].TrimEnd('\r'));
    }

    [Fact]
    [Scenario(TestScenario.Boundary)]
    public void GeneratedFile_WithoutFileDefines_DefinesNothingAndRemovesTheCall()
    {
        var kernels = GetSource("ConditionalCallCase__PlainKernels.g.cs");

        Assert.DoesNotContain("#define CONDITIONAL", kernels, StringComparison.Ordinal);
        Assert.DoesNotContain("Kept(", kernels, StringComparison.Ordinal);
    }

    [Fact]
    [Scenario(TestScenario.HappyPath)]
    public void ManagedBodies_KeepOnlyTheCallsCSharpKeeps()
    {
        var kernels = GetSource("ConditionalCallCase__DefineKernels.g.cs");
        var managedVersion = GetSource("ConditionalCallCase__CallOps.DeviceStateMachines.g.cs");

        Assert.Contains("CallOps.Kept(output)", kernels, StringComparison.Ordinal);
        Assert.DoesNotContain("CallOps.Removed(", kernels, StringComparison.Ordinal);
        Assert.Contains("CallOps.Kept(output)", managedVersion, StringComparison.Ordinal);
        Assert.DoesNotContain("CallOps.Removed(", managedVersion, StringComparison.Ordinal);
        Assert.Contains("k++)", managedVersion, StringComparison.Ordinal);
    }

    // The generated file decides again: Kept, defined only by the #define of the user's file, stays a call there
    [Fact]
    [Scenario(TestScenario.Boundary)]
    public void GeneratedTree_KeptCall_IsNotRemovedByCSharp()
    {
        var output = s_run.Value.Output;
        var tree = output.SyntaxTrees.Single(t => t.FilePath.EndsWith("ConditionalCallCase__DefineKernels.g.cs",
            StringComparison.Ordinal));
        var model = output.GetSemanticModel(tree);
        var kept = tree.GetRoot()
            .DescendantNodes()
            .OfType<InvocationExpressionSyntax>()
            .Where(static i => i.Expression is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Kept" })
            .ToList();

        Assert.NotEmpty(kept);
        Assert.All(kept, call => Assert.False(RemovedCalls.IsRemoved(call, model)));
    }

    // The inlined iterator body follows the file it was written in, where Marker is removed
    [Fact]
    [Scenario(TestScenario.Boundary)]
    public void NativeSource_IteratorOfFileWithoutDefine_LeavesOutTheCall()
    {
        var kernels = GetSource("ConditionalCallCase__DefineKernels.g.cs");
        var start = kernels.IndexOf("IteratorKernel_Source = @\"", StringComparison.Ordinal);
        Assert.True(start >= 0, kernels);
        var end = kernels.IndexOf("\";", start, StringComparison.Ordinal);
        var source = kernels[start..end];

        Assert.DoesNotContain("Marker(", source, StringComparison.Ordinal);
        Assert.DoesNotContain("#error", source, StringComparison.Ordinal);
    }
}
