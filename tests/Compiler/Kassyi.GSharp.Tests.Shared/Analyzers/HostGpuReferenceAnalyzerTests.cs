using Kassyi.GSharp.Compiler.Diagnostics;
using Microsoft.CodeAnalysis.Diagnostics;
using static Kassyi.GSharp.Tests.Shared.Helpers.DiagnosticOrigin;

namespace Kassyi.GSharp.Tests.Shared.Analyzers;

[Category(TestCategory.Compiler)]
public class HostGpuReferenceAnalyzerTests : TranspilerTestBase
{
    private static readonly HostGpuReferenceAnalyzer s_analyzer = new();

    [Fact]
    [Scenario(TestScenario.SadPath)]
    public async Task GpuKernelDirectInvocation_DirectCallFromHost_ReportsGSH0031()
    {
        await GeneratorTestRunner.TestAnalyzer("Analyzers/DirectGpuKernelInvocation.cs", s_analyzer)
                               .ReportsErrorsAsync(GSharpDiagnostics.DirectGpuKernelInvocation);
    }

    [Fact]
    [Scenario(TestScenario.Boundary)]
    public async Task GpuKernelDirectInvocation_NestedCalls_FollowEnclosingFunction()
    {
        var diagnostics = await GeneratorTestRunner.TestAnalyzer("Analyzers/DirectGpuKernelInvocationNested.cs", s_analyzer)
                                                 .GetDiagnosticsAsync();

        // Only the lambda in host code is reported; lambdas and local functions inside GPU functions are device code.
        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal(GSharpDiagnostics.DirectGpuKernelInvocation.Id, diagnostic.Id);
        var line = diagnostic.Location.GetLineSpan().StartLinePosition.Line;
        Assert.Contains("NestedInvocationKernels.TargetKernel()",
            diagnostic.Location.SourceTree?.GetText().Lines[line].ToString() ?? string.Empty);
    }

    // Each form that runs or references a kernel from host code, at the reference: a call (lines 134, 142 in a lambda,
    // 173 kept by [Conditional]), a method group in a field initializer, a conversion, a delegate creation, a cast, a
    // natural type, an argument and an event subscription (128, 135-140), a function pointer (141), the GetEnumerator
    // of a foreach, a Deconstruct of a deconstruction and of a positional pattern, the Add of each collection
    // initializer element and a GetAwaiter (147-157), an operator, a conversion operator and the two accessors of a
    // property (162-165). Not reported: device code (39-40), nameof (170), a call that C# removes and a method group in
    // the arguments of one (171-172)
    [Fact]
    [Scenario(TestScenario.SadPath)]
    public async Task HostReference_EveryForm_ReportsGsh0031AtTheReference()
    {
        var diagnostics = await GeneratorTestRunner.TestAnalyzer("Analyzers/HostKernelReferences.cs", s_analyzer)
                                                 .GetDiagnosticsAsync();

        Assert.Equal(
            [
                (Analyzer, 128, 53, 128, 72),
                (Analyzer, 134, 9, 134, 31),
                (Analyzer, 135, 27, 135, 46),
                (Analyzer, 136, 41, 136, 60),
                (Analyzer, 137, 35, 137, 54),
                (Analyzer, 138, 23, 138, 42),
                (Analyzer, 139, 31, 139, 50),
                (Analyzer, 140, 20, 140, 39),
                (Analyzer, 141, 42, 141, 62),
                (Analyzer, 142, 29, 142, 51),
                (Analyzer, 147, 30, 147, 35),
                (Analyzer, 151, 9, 151, 26),
                (Analyzer, 152, 21, 152, 28),
                (Analyzer, 156, 35, 156, 37),
                (Analyzer, 156, 39, 156, 40),
                (Analyzer, 157, 9, 157, 23),
                (Analyzer, 162, 19, 162, 24),
                (Analyzer, 163, 21, 163, 27),
                (Analyzer, 164, 20, 164, 41),
                (Analyzer, 165, 9, 165, 30),
                (Analyzer, 173, 9, 173, 35)
            ],
            ToReported(diagnostics).Ranges(GSharpDiagnostics.DirectGpuKernelInvocation.Id));
        Assert.All(diagnostics, static d => Assert.Equal(GSharpDiagnostics.DirectGpuKernelInvocation.Id, d.Id));
    }

    // The message of the forms reported before stays as it was
    [Fact]
    [Scenario(TestScenario.SadPath)]
    public async Task HostReference_MethodGroup_KeepsTheMessageOfACall()
    {
        var diagnostics = await GeneratorTestRunner.TestAnalyzer("Analyzers/HostKernelReferences.cs", s_analyzer)
                                                 .GetDiagnosticsAsync();

        const string Expected =
            "Do not call [GpuKernel] method 'K' directly. Use the generated 'LaunchK' launcher method instead.";
        Assert.Equal(Expected, ToReported(diagnostics).Single(static d => d.StartLine == 134).Message);
        Assert.Equal(Expected, ToReported(diagnostics).Single(static d => d.StartLine == 135).Message);
    }

    // Generated code is analyzed: a *.g.cs file, a file with an <auto-generated/> header and the output of another
    // generator. Only the trees that G#'s own generators add are left out
    [Theory]
    [InlineData("Callers/GeneratedCodeCaller.g.cs", "", true)]
    [InlineData("Callers/GeneratedCodeCaller.cs", "// <auto-generated/>\n", true)]
    [InlineData("Other.Generators/Other.Generators.CallerGenerator/GeneratedCodeCaller.g.cs", "", true)]
    [InlineData("Kassyi.GSharp.Compiler/Kassyi.GSharp.Compiler.GpuKernelGenerator/GeneratedCodeCaller.g.cs", "", false)]
    [InlineData(@"C:\obj\Kassyi.GSharp.Compiler\Kassyi.GSharp.Compiler.GpuKernelGenerator\Caller.g.cs", "", false)]
    [Scenario(TestScenario.Boundary)]
    public async Task HostReference_InGeneratedCode_IsReportedUnlessGSharpOutput(
        string path,
        string header,
        bool reported)
    {
        var compilation = RoslynTestUtility.CreateCompilationAt(
            ("Kernels/GeneratedCodeKernel.cs", RoslynTestUtility.ReadTestCase("Analyzers/GeneratedCodeKernel.cs")),
            (path, header + RoslynTestUtility.ReadTestCase("Analyzers/GeneratedCodeCaller.cs")));

        var diagnostics = await compilation
            .WithAnalyzers([s_analyzer], new AnalyzerOptions(ImmutableArray<AdditionalText>.Empty))
            .GetAnalyzerDiagnosticsAsync();

        var line = header.Length == 0 ? 7 : 8;
        Assert.Equal(
            reported ? [(path, line, 9, line, 34)] : Array.Empty<(string, int, int, int, int)>(),
            diagnostics.Select(static d => d.Location.GetLineSpan())
                       .Select(static s => (s.Path, s.StartLinePosition.Line + 1, s.StartLinePosition.Character + 1,
                           s.EndLinePosition.Line + 1, s.EndLinePosition.Character + 1)));
    }

    // The trees that the generator adds in process (an empty base directory) are G#'s own output, the user's are not
    [Fact]
    [Scenario(TestScenario.HappyPath)]
    public void GSharpOwnOutput_TreesThatTheGeneratorAdds_AreOwnOutput()
    {
        var input = RoslynTestUtility.CreateCompilationAt(
            "Kernels/GeneratedCodeKernel.cs",
            RoslynTestUtility.ReadTestCase("Analyzers/GeneratedCodeKernel.cs"));

        var (_, output, _) = GeneratorTestRunner.RunGenerator(input);

        var generated = output.SyntaxTrees.Except(input.SyntaxTrees).ToList();
        Assert.NotEmpty(generated);
        Assert.All(generated, static tree => Assert.True(GSharpGeneratedTrees.IsOwnOutput(tree), tree.FilePath));
        Assert.All(
            input.SyntaxTrees,
            static tree => Assert.False(GSharpGeneratedTrees.IsOwnOutput(tree), tree.FilePath));
    }

    // #1728: C# removes the calls of RemovedKernel (lines 32 and 41); the calls of KeptKernel stay and are reported,
    // GSH0003 in the kernel (33) and GSH0031 in host code (42)
    [Theory]
    [InlineData("Cpu")]
    [InlineData("Cuda")]
    [Scenario(TestScenario.Boundary)]
    public async Task KernelCall_RemovedByConditional_IsNotReported(string dialect)
    {
        var diagnostics =
            await KernelDiagnostics.RunTestCaseAsync("Diagnostics/KernelCallRemovedByConditional.cu.cs", dialect);

        Assert.Equal([(Analyzer, 33, 9, 33, 25)], diagnostics.Ranges(GSharpDiagnostics.UnsupportedSyntax.Id));
        Assert.Equal([(Analyzer, 42, 9, 42, 63)], diagnostics.Ranges(GSharpDiagnostics.DirectGpuKernelInvocation.Id));
        Assert.Equal(2, diagnostics.Length);
    }

    private static ImmutableArray<ReportedDiagnostic> ToReported(ImmutableArray<Diagnostic> diagnostics) =>
        diagnostics.Select(static d => ReportedDiagnostic.From(Analyzer, d))
                   .OrderBy(static d => d.StartLine)
                   .ThenBy(static d => d.StartColumn)
                   .ToImmutableArray();
}
