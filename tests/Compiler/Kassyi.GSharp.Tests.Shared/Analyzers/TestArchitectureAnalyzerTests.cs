using Kassyi.GSharp.Tests.Generators;
using Kassyi.GSharp.Tests.Infrastructure;

namespace Kassyi.GSharp.Tests.Shared.Analyzers;

[Category(TestCategory.Compiler)]
public class TestArchitectureAnalyzerTests : AnalyzerTestBase
{
    [Fact]
    [Scenario(TestScenario.HappyPath)]
    public async Task Test_ValidTestArchitecture_NoDiagnostics()
    {
        await VerifyAnalyzerFromFileAsync("TestArchitecture/ValidTestArchitecture.cs", new TestArchitectureAnalyzer(), nameof(Test_ValidTestArchitecture_NoDiagnostics));
    }

    [Fact]
    [Scenario(TestScenario.SadPath)]
    public async Task Test_MissingCategory_ReportsError()
    {
        await VerifyAnalyzerFromFileAsync("TestArchitecture/MissingCategory.cs", new TestArchitectureAnalyzer(), nameof(Test_MissingCategory_ReportsError));
    }

    // HNT0002: a class-level Category covers [SkippableFact] and [Theory] methods.
    [Fact]
    [Scenario(TestScenario.HappyPath)]
    public async Task Test_ClassCategoryOnly_NoDiagnostics()
    {
        await VerifyAnalyzerFromFileAsync(
            "TestArchitecture/ClassCategoryOnly.cs",
            new TestArchitectureAnalyzer(),
            nameof(Test_ClassCategoryOnly_NoDiagnostics)
        );
    }

    // HNT0002: reported in a file marked <auto-generated/>, the way .editorconfig marks tests/**.
    [Fact]
    [Scenario(TestScenario.SadPath)]
    public async Task Test_AutoGeneratedMissingCategory_ReportsError()
    {
        await VerifyAnalyzerFromFileAsync(
            "TestArchitecture/AutoGeneratedMissingCategory.cs",
            new TestArchitectureAnalyzer(),
            nameof(Test_AutoGeneratedMissingCategory_ReportsError)
        );
    }

    // HNT0008: raw Xunit.TraitAttribute is reported on classes and methods; [Trait("Category", ...)] no longer satisfies HNT0002.
    [Fact]
    [Scenario(TestScenario.SadPath)]
    public async Task Test_RawTraitAttribute_ReportsError()
    {
        await VerifyAnalyzerFromFileAsync(
            "TestArchitecture/RawTraitAttribute.cs",
            new TestArchitectureAnalyzer(),
            nameof(Test_RawTraitAttribute_ReportsError)
        );
    }
}
