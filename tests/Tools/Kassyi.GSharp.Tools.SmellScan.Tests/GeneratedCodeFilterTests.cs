#nullable enable
namespace Kassyi.GSharp.Tools.SmellScan.Tests;

public class GeneratedCodeFilterTests
{
    [Theory]
    [InlineData("src/A/Foo.g.cs", true)]
    [InlineData("src/A/Foo.G.CS", true)]
    [InlineData("src/A/Foo.g.i.cs", true)]
    [InlineData("src/A/Form1.designer.cs", true)]
    [InlineData("src/A/Foo.generated.cs", true)]
    [InlineData("TemporaryGeneratedFile_036C0B5B.cs", true)]
    [InlineData("src/A/Foo.cs", false)]
    [InlineData("src/A/debug.cs", false)]
    [InlineData("src/A/Big.cs", false)]
    [InlineData("src/g.cs/Foo.cs", false)]
    [TestTarget(ExecutionTarget.CpuExecution)]
    [Category(TestCategory.Unit)]
    [Scenario(TestScenario.Boundary)]
    public void HasGeneratedName_FileName_FollowsTheRoslynSuffixes(string path, bool generated)
    {
        Assert.Equal(generated, GeneratedCodeFilter.HasGeneratedName(path));
    }

    [Fact]
    [TestTarget(ExecutionTarget.CpuExecution)]
    [Category(TestCategory.Unit)]
    [Scenario(TestScenario.HappyPath)]
    public void Parse_AutoGeneratedHeader_MarksTheFileGeneratedWithoutVariants()
    {
        var parsed = SyntaxInput.Parse("GeneratedWithHeader.cs", TestCaseFiles.Read("GeneratedWithHeader.cs"));

        Assert.True(parsed.IsGenerated);
        Assert.Empty(parsed.Variants);
    }

    [Fact]
    [TestTarget(ExecutionTarget.CpuExecution)]
    [Category(TestCategory.Unit)]
    [Scenario(TestScenario.SadPath)]
    public void Parse_CommentAfterTheFirstToken_DoesNotMarkTheFileGenerated()
    {
        var parsed = SyntaxInput.Parse("CommentMentionsGenerated.cs", TestCaseFiles.Read("CommentMentionsGenerated.cs"));

        Assert.False(parsed.IsGenerated);
        Assert.Single(parsed.Variants);
    }

    [Fact]
    [TestTarget(ExecutionTarget.CpuExecution)]
    [Category(TestCategory.Unit)]
    [Scenario(TestScenario.HappyPath)]
    public void Scan_GeneratedFiles_AreCountedAndNeverMeasured()
    {
        using var workspace = new ScanWorkspace();
        workspace.Add("GeneratedWithHeader.cs", "src/Header.cs");
        workspace.Add("CommentMentionsGenerated.cs", "src/Comment.cs");
        workspace.Add("CommentMentionsGenerated.cs", "src/Named.g.cs");

        var report = workspace.Scan("Config/low-thresholds.yml", 1, "src/Header.cs", "src/Comment.cs", "src/Named.g.cs");

        Assert.Equal(2, report.ExcludedGenerated);
        Assert.Equal(1, report.Files);
        foreach (var finding in report.Findings)
        {
            Assert.Equal("src/Comment.cs", finding.Measurement.Path);
        }
    }
}
