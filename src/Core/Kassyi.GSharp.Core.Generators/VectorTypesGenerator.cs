using Kassyi.GSharp.Compiler;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Kassyi.GSharp.Core.Generators;

/// <summary>
/// Incremental source generator that emits CUDA-compatible vector types (e.g., Float2, Int4, Double3).
/// </summary>
[Generator]
public class VectorTypesGenerator : IIncrementalGenerator
{
    private static readonly VectorTypeDefinition[] SupportedTypes =
    [
        new("Float", "float", 4, "float", "single-precision floating-point"),
        new("Int", "int", 4, "int", "32-bit signed integer"),
        new("UInt", "uint", 4, "uint", "32-bit unsigned integer"),
        new("Double", "double", 8, "double", "double-precision floating-point"),
        new("Long", "long", 8, "long", "64-bit signed integer"),
        new("ULong", "ulong", 8, "ulong", "64-bit unsigned integer"),
    ];

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(GenerateSource);
    }

    private static void GenerateSource(IncrementalGeneratorPostInitializationContext ctx)
    {
        using var sw = new SourceWriter();
        EmitHeader(sw);

        foreach (var type in SupportedTypes)
        {
            EmitVectorType(sw, in type);
        }

        ctx.AddSource("VectorTypes.g.cs", SourceText.From(sw.ToString(), Encoding.UTF8));
    }

    private static void EmitHeader(SourceWriter sw)
    {
        sw.AppendLine("// <auto-generated>");
        sw.AppendLine("// This file is auto-generated by Kassyi.GSharp.Core.Generators (VectorTypesGenerator).");
        sw.AppendLine("// Do not modify this file manually.");
        sw.AppendLine("// </auto-generated>");
        sw.AppendLine("using System.Runtime.InteropServices;");
        sw.AppendLine();
        sw.AppendLine("// ReSharper disable UnusedMember.Global");
        sw.AppendLine("#pragma warning disable IDE0051 // Remove unused private members");
        sw.AppendLine();
        sw.AppendLine("namespace Kassyi.GSharp.Core;");
        sw.AppendLine();
    }

    private static void EmitVectorType(SourceWriter sw, in VectorTypeDefinition type)
    {
        sw.AppendLine($"// --- {type.Name} ---");
        sw.AppendLine();

        for (int dim = 2; dim <= 4; dim++)
        {
            EmitVectorStruct(sw, in type, dim);
        }
    }

    private static void EmitVectorStruct(SourceWriter sw, in VectorTypeDefinition type, int dim)
    {
        int totalSize = type.Size * dim;
        int align = CalculateAlignment(type.Size, dim);

        EmitXmlDocumentation(sw, in type, dim, totalSize, align);
        EmitStructHeader(sw, in type, dim);
        EmitStructMembers(sw, in type, dim);

        sw.AppendLine("}");
        sw.AppendLine();
    }

    private static int CalculateAlignment(int elementSize, int dim) =>
        dim == 3 ? elementSize : (dim == 2 ? elementSize * 2 : (elementSize * 4 > 16 ? 16 : elementSize * 4));

    private static void EmitXmlDocumentation(
        SourceWriter sw,
        in VectorTypeDefinition type,
        int dim,
        int totalSize,
        int align)
    {
        EmitXmlDocSummary(sw, in type, dim);
        EmitXmlDocParams(sw, dim);
        EmitXmlDocRemarks(sw, totalSize, align);
    }

    private static void EmitXmlDocSummary(SourceWriter sw, in VectorTypeDefinition type, int dim)
    {
        string cudaType = type.CudaType + dim;
        sw.AppendLine("/// <summary>");
        sw.AppendLine(
            $"/// Represents a {dim}-component vector of {type.Desc} values " +
            $"corresponding to the CUDA native <c>{cudaType}</c> type.");
        sw.AppendLine("/// </summary>");
    }

    private static void EmitXmlDocParams(SourceWriter sw, int dim)
    {
        if (dim >= 2)
        {
            sw.AppendLine("/// <param name=\"x\">The X component of the vector.</param>");
        }

        if (dim >= 2)
        {
            sw.AppendLine("/// <param name=\"y\">The Y component of the vector.</param>");
        }

        if (dim >= 3)
        {
            sw.AppendLine("/// <param name=\"z\">The Z component of the vector.</param>");
        }

        if (dim >= 4)
        {
            sw.AppendLine("/// <param name=\"w\">The W component of the vector.</param>");
        }
    }

    private static void EmitXmlDocRemarks(SourceWriter sw, int totalSize, int align)
    {
        sw.AppendLine("/// <remarks>");
        sw.AppendLine(
            $"/// <para><b>Memory Layout:</b> {totalSize} bytes, " +
            $"{align}-byte aligned (blittable value type).</para>");
        sw.AppendLine(
            "/// <para><b>Execution Target:</b> " +
            "Usable on both Host (CPU) and Device (GPU kernels).</para>");
        sw.AppendLine("/// </remarks>");
    }

    private static void EmitStructHeader(SourceWriter sw, in VectorTypeDefinition type, int dim)
    {
        string structName = type.Name + dim;
        sw.AppendLine("[StructLayout(LayoutKind.Sequential)]");
        sw.AppendExcludeFromCodeCoverageAttribute();
        sw.Append($"public struct {structName}(");
        sw.Append($"{type.Type} x, {type.Type} y");
        if (dim >= 3)
        {
            sw.Append($", {type.Type} z");
        }

        if (dim >= 4)
        {
            sw.Append($", {type.Type} w");
        }

        sw.AppendLine(")");
        sw.AppendLine("{");
    }

    private static void EmitStructMembers(SourceWriter sw, in VectorTypeDefinition type, int dim)
    {
        sw.AppendLine("/// <summary>The X component of the vector.</summary>");
        sw.AppendLine($"public {type.Type} X = x;");
        sw.AppendLine();
        sw.AppendLine("/// <summary>The Y component of the vector.</summary>");
        sw.AppendLine($"public {type.Type} Y = y;");

        if (dim >= 3)
        {
            sw.AppendLine();
            sw.AppendLine("/// <summary>The Z component of the vector.</summary>");
            sw.AppendLine($"public {type.Type} Z = z;");
        }

        if (dim >= 4)
        {
            sw.AppendLine();
            sw.AppendLine("/// <summary>The W component of the vector.</summary>");
            sw.AppendLine($"public {type.Type} W = w;");
        }
    }

    private readonly record struct VectorTypeDefinition(
        string Name,
        string Type,
        int Size,
        string CudaType,
        string Desc);
}
