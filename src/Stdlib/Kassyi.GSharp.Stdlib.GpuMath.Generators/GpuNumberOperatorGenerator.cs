using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Kassyi.GSharp.Stdlib.GpuMath.Generators;

/// <summary>
/// Source generator that automatically implements operators for GPU numbers based on the <c>GenerateGpuNumberOperatorsAttribute</c>.
/// </summary>
[Generator]
public class GpuNumberOperatorGenerator : IIncrementalGenerator
{
    /// <summary>
    /// The fully qualified name of the target attribute.
    /// </summary>
    private const string AttributeName = "Kassyi.GSharp.Stdlib.GpuMath.BigNum.GenerateGpuNumberOperatorsAttribute";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var structDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => IsSyntaxTargetForGeneration(s),
                transform: static (ctx, _) => GetSemanticTargetForGeneration(ctx))
            .Where(static m => m is not null)
            .Select(static (m, _) => m ?? throw new InvalidOperationException("Filtered struct declaration was null"));

        var compilationAndStructs = context.CompilationProvider.Combine(structDeclarations.Collect());

        context.RegisterSourceOutput(compilationAndStructs,
            static (spc, source) => Execute(source.Left, source.Right, spc));
    }

    private static bool IsSyntaxTargetForGeneration(SyntaxNode node) =>
        node is StructDeclarationSyntax { AttributeLists.Count: > 0 };

    private static StructDeclarationSyntax? GetSemanticTargetForGeneration(GeneratorSyntaxContext context)
    {
        var structDeclaration = (StructDeclarationSyntax)context.Node;
        foreach (var attributeListSyntax in structDeclaration.AttributeLists)
        {
            foreach (var attributeSyntax in attributeListSyntax.Attributes)
            {
                if (context.SemanticModel.GetSymbolInfo(attributeSyntax).Symbol is not IMethodSymbol attributeSymbol)
                {
                    continue;
                }

                var attributeContainingTypeSymbol = attributeSymbol.ContainingType;
                // Suppress RS0030: Compile-time allocation is acceptable here to avoid linking compiler helper dependencies.
#pragma warning disable RS0030
                var fullName = attributeContainingTypeSymbol.ToDisplayString();
#pragma warning restore RS0030
                if (fullName == AttributeName)
                {
                    return structDeclaration;
                }
            }
        }

        return null;
    }

    private static void Execute(Compilation compilation, ImmutableArray<StructDeclarationSyntax> structs,
        SourceProductionContext context)
    {
        if (structs.IsDefaultOrEmpty)
        {
            return;
        }

        var seen = new HashSet<StructDeclarationSyntax>();

        foreach (var structSyntax in structs)
        {
            if (!seen.Add(structSyntax))
            {
                continue;
            }

            var semanticModel = compilation.GetSemanticModel(structSyntax.SyntaxTree);
            if (semanticModel.GetDeclaredSymbol(structSyntax) is not INamedTypeSymbol structSymbol)
            {
                continue;
            }

            // Suppress RS0030: Compile-time allocation is acceptable here to avoid linking compiler helper dependencies.
#pragma warning disable RS0030
            var namespaceName = structSymbol.ContainingNamespace.ToDisplayString();
#pragma warning restore RS0030
            var structName = structSymbol.Name;

            var source = GenerateSource(namespaceName, structName);
            context.AddSource($"{structName}.Operators.g.cs", SourceText.From(source, Encoding.UTF8));
        }
    }

    private static string GenerateSource(string namespaceName, string structName)
    {
        var isAstNode = structName == "GpuBigUInt";
        var returnType = isAstNode ? "Kassyi.GSharp.Stdlib.GpuMath.BigNum.Expressions.GpuBigUIntExpr" : structName;

        using var writer = new SourceWriter();
        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line($"namespace {namespaceName}");
        using (writer.Scope())
        {
            inheritdoc();
            writer.Line($"public partial struct {structName}");
            using (writer.Scope())
            {
                // Supported by both AST and Value-types
                inheritdoc();
                writer.Line(
                    $"public static {returnType} operator +({structName} left, {structName} right) => {operatorBody("Add")};");
                inheritdoc();
                writer.Line(
                    $"public static {returnType} operator -({structName} left, {structName} right) => {operatorBody("Sub")};");

                // AST only
                if (isAstNode)
                {
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator *({structName} left, {structName} right) => {operatorBody("Mul")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator /({structName} left, {structName} right) => {operatorBody("Div")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator %({structName} left, {structName} right) => {operatorBody("Mod")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator &({structName} left, {structName} right) => {operatorBody("BitwiseAnd")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator |({structName} left, {structName} right) => {operatorBody("BitwiseOr")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator ^({structName} left, {structName} right) => {operatorBody("BitwiseXor")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator <<({structName} left, int shift) => {shiftBody("ShiftLeft")};");
                    inheritdoc();
                    writer.Line(
                        $"public static {returnType} operator >>({structName} left, int shift) => {shiftBody("ShiftRight")};");
                }

                // Comparisons (Supported by both)
                inheritdoc();
                writer.Line(
                    $"public static bool operator ==({structName} left, {structName} right) => left.Equals(right);");
                inheritdoc();
                writer.Line(
                    $"public static bool operator !=({structName} left, {structName} right) => !left.Equals(right);");
                inheritdoc();
                writer.Line(
                    $"public static bool operator <({structName} left, {structName} right) => left.CompareTo(right) < 0;");
                inheritdoc();
                writer.Line(
                    $"public static bool operator >({structName} left, {structName} right) => left.CompareTo(right) > 0;");
                inheritdoc();
                writer.Line(
                    $"public static bool operator <=({structName} left, {structName} right) => left.CompareTo(right) <= 0;");
                inheritdoc();
                writer.Line(
                    $"public static bool operator >=({structName} left, {structName} right) => left.CompareTo(right) >= 0;");
            }
        }

        return writer.ToString();

        string shiftBody(string op) => isAstNode
            ? "new(new Kassyi.GSharp.Stdlib.GpuMath.BigNum.Expressions.ShiftLeftExpression(left, shift))".Replace(
                "ShiftLeft", op)
            : $"new {structName}(left.Value {GetOperatorSymbol(op)} shift)";

        string operatorBody(string op) => isAstNode
            ? "new(new Kassyi.GSharp.Stdlib.GpuMath.BigNum.Expressions.AddExpression(left, right))".Replace("Add", op)
            : $"new {structName}(left.Value {GetOperatorSymbol(op)} right.Value)";

        void inheritdoc() => writer.Line("/// <inheritdoc/>");
    }

    private static string GetOperatorSymbol(string opName)
    {
        return opName switch
        {
            "Add" => "+",
            "Sub" => "-",
            "Mul" => "*",
            "Div" => "/",
            "Mod" => "%",
            "BitwiseAnd" => "&",
            "BitwiseOr" => "|",
            "BitwiseXor" => "^",
            "ShiftLeft" => "<<",
            "ShiftRight" => ">>",
            _ => ""
        };
    }
}
