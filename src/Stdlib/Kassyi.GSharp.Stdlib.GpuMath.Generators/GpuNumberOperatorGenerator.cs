using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Kassyi.GSharp.Stdlib.GpuMath.Generators;

/// <summary>
/// Source generator that automatically implements operators for GPU numbers based on the
/// <c>GenerateGpuNumberOperatorsAttribute</c>.
/// </summary>
[Generator]
public class GpuNumberOperatorGenerator : IIncrementalGenerator
{
    /// <summary>
    /// The fully qualified name of the target attribute.
    /// </summary>
    private const string AttributeName = "Kassyi.GSharp.Stdlib.GpuMath.BigNum.GenerateGpuNumberOperatorsAttribute";

    private const string ExpressionsNamespace = "Kassyi.GSharp.Stdlib.GpuMath.BigNum.Expressions";

    // The operators only the expression type (GpuBigUInt) has, by the name of their expression node.
    private static readonly string[] s_expressionOnlyOperators =
        ["Mul", "Div", "Mod", "BitwiseAnd", "BitwiseOr", "BitwiseXor"];

    private static readonly string[] s_expressionOnlyShifts = ["ShiftLeft", "ShiftRight"];

    private static readonly string[] s_orderingOperators = ["<", ">", "<=", ">="];

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var structDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => IsSyntaxTargetForGeneration(s),
                transform: static (ctx, _) => GetSemanticTargetForGeneration(ctx))
            .Where(static m => m is not null)
            .Select(static (m, _) => m ?? throw new InvalidOperationException("Filtered struct declaration was null"));

        var compilationAndStructs = context.CompilationProvider.Combine(structDeclarations.Collect());

        context.RegisterSourceOutput(compilationAndStructs,
            static (spc, source) => Execute(source.Left, source.Right, spc));
    }

    private static bool IsSyntaxTargetForGeneration(SyntaxNode node) =>
        node is StructDeclarationSyntax { AttributeLists.Count: > 0 };

    private static StructDeclarationSyntax? GetSemanticTargetForGeneration(GeneratorSyntaxContext context)
    {
        var structDeclaration = (StructDeclarationSyntax)context.Node;
        foreach (var attributeListSyntax in structDeclaration.AttributeLists)
        {
            foreach (var attributeSyntax in attributeListSyntax.Attributes)
            {
                if (context.SemanticModel.GetSymbolInfo(attributeSyntax).Symbol is not IMethodSymbol attributeSymbol)
                {
                    continue;
                }

                var attributeContainingTypeSymbol = attributeSymbol.ContainingType;
                // Suppress RS0030: Compile-time allocation is acceptable here to avoid linking compiler helper
                // dependencies.
#pragma warning disable RS0030
                var fullName = attributeContainingTypeSymbol.ToDisplayString();
#pragma warning restore RS0030
                if (fullName == AttributeName)
                {
                    return structDeclaration;
                }
            }
        }

        return null;
    }

    private static void Execute(Compilation compilation, ImmutableArray<StructDeclarationSyntax> structs,
        SourceProductionContext context)
    {
        if (structs.IsDefaultOrEmpty)
        {
            return;
        }

        var seen = new HashSet<StructDeclarationSyntax>();

        foreach (var structSyntax in structs)
        {
            if (!seen.Add(structSyntax))
            {
                continue;
            }

            var semanticModel = compilation.GetSemanticModel(structSyntax.SyntaxTree);
            if (semanticModel.GetDeclaredSymbol(structSyntax) is not INamedTypeSymbol structSymbol)
            {
                continue;
            }

            // Suppress RS0030: Compile-time allocation is acceptable here to avoid linking compiler helper dependencies.
#pragma warning disable RS0030
            var namespaceName = structSymbol.ContainingNamespace.ToDisplayString();
#pragma warning restore RS0030
            var structName = structSymbol.Name;

            var source = GenerateSource(namespaceName, structName);
            context.AddSource($"{structName}.Operators.g.cs", SourceText.From(source, Encoding.UTF8));
        }
    }

    private static string GenerateSource(string namespaceName, string structName)
    {
        var target = new OperatorTarget(structName, isAstNode: structName == "GpuBigUInt");

        using var writer = new SourceWriter();
        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line($"namespace {namespaceName}");
        using (writer.Scope())
        {
            WriteInheritDoc(writer);
            writer.Line($"public partial struct {structName}");
            using (writer.Scope())
            {
                // Supported by both AST and Value-types
                WriteBinaryOperator(writer, target, "Add");
                WriteBinaryOperator(writer, target, "Sub");

                // AST only
                if (target.IsAstNode)
                {
                    WriteExpressionOnlyOperators(writer, target);
                }

                WriteComparisonOperators(writer, target);
            }
        }

        return writer.ToString();
    }

    private static void WriteExpressionOnlyOperators(SourceWriter writer, OperatorTarget target)
    {
        foreach (var op in s_expressionOnlyOperators)
        {
            WriteBinaryOperator(writer, target, op);
        }

        foreach (var op in s_expressionOnlyShifts)
        {
            WriteShiftOperator(writer, target, op);
        }
    }

    // public static <return type> operator <symbol>(<struct> left, <struct> right) => <body>;
    private static void WriteBinaryOperator(SourceWriter writer, OperatorTarget target, string op)
    {
        var symbol = GetOperatorSymbol(op);
        var body = target.IsAstNode
            ? $"new(new {ExpressionsNamespace}.{op}Expression(left, right))"
            : $"new {target.StructName}(left.Value {symbol} right.Value)";
        var name = target.StructName;
        WriteInheritDoc(writer);
        writer.Line($"public static {target.ReturnType} operator {symbol}({name} left, {name} right) => {body};");
    }

    // public static <return type> operator <symbol>(<struct> left, int shift) => <body>;
    private static void WriteShiftOperator(SourceWriter writer, OperatorTarget target, string op)
    {
        var symbol = GetOperatorSymbol(op);
        var body = target.IsAstNode
            ? $"new(new {ExpressionsNamespace}.{op}Expression(left, shift))"
            : $"new {target.StructName}(left.Value {symbol} shift)";
        var name = target.StructName;
        WriteInheritDoc(writer);
        writer.Line($"public static {target.ReturnType} operator {symbol}({name} left, int shift) => {body};");
    }

    private static void WriteComparisonOperators(SourceWriter writer, OperatorTarget target)
    {
        // Comparisons (Supported by both). == and != compare values: GpuBigUInt.Equals is the identity of the
        // buffer (#638), while the fixed-width types compare values in Equals as well
        var equality = target.IsAstNode ? "left.CompareTo(right) == 0" : "left.Equals(right)";
        var inequality = target.IsAstNode ? "left.CompareTo(right) != 0" : "!left.Equals(right)";
        WriteComparisonOperator(writer, target, "==", equality);
        WriteComparisonOperator(writer, target, "!=", inequality);
        foreach (var symbol in s_orderingOperators)
        {
            WriteComparisonOperator(writer, target, symbol, $"left.CompareTo(right) {symbol} 0");
        }
    }

    // public static bool operator <symbol>(<struct> left, <struct> right) => <body>;
    private static void WriteComparisonOperator(SourceWriter writer, OperatorTarget target, string symbol, string body)
    {
        var name = target.StructName;
        WriteInheritDoc(writer);
        writer.Line($"public static bool operator {symbol}({name} left, {name} right) => {body};");
    }

    private static void WriteInheritDoc(SourceWriter writer) => writer.Line("/// <inheritdoc/>");

    private static string GetOperatorSymbol(string opName)
    {
        return opName switch
        {
            "Add" => "+",
            "Sub" => "-",
            "Mul" => "*",
            "Div" => "/",
            "Mod" => "%",
            "BitwiseAnd" => "&",
            "BitwiseOr" => "|",
            "BitwiseXor" => "^",
            "ShiftLeft" => "<<",
            "ShiftRight" => ">>",
            _ => ""
        };
    }

    // The struct the operators are generated for: GpuBigUInt (IsAstNode) builds expression nodes, the fixed-width types
    // compute values.
    private readonly struct OperatorTarget(string structName, bool isAstNode)
    {
        public string StructName { get; } = structName;

        public bool IsAstNode { get; } = isAstNode;

        public string ReturnType => IsAstNode ? ExpressionsNamespace + ".GpuBigUIntExpr" : StructName;
    }
}
