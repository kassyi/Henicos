            0x2a, 0x20, 0x53, 0xfa, 0x2c, 0x39, 0xcc, 0xc6, 0x4e, 0xc7, 0xfd, 0x77, 0x92, 0xac, 0x03, 0xfa,
        ],
    ];

    /// <summary>
    /// Checks that <paramref name="publicKey"/> is a canonical, decompressible point (RFC 8032 Section 5.1.3)
    /// and is not one of the 8 small-order points.
    /// </summary>
    public static Ed25519PublicKeyStatus Validate(ReadOnlySpan<byte> publicKey)
    {
        if (publicKey.Length != PublicKeySize)
        {
            return Ed25519PublicKeyStatus.InvalidLength;
        }

        if (!Ed25519Field.TryDecodePoint(publicKey, out _, out _))
        {
            return Ed25519PublicKeyStatus.NotOnCurve;
        }

        // A successfully decoded point has a canonical encoding, so a byte comparison covers every small-order point.
        foreach (var encoding in s_smallOrderEncodings)
        {
            if (publicKey.SequenceEqual(encoding))
            {
                return Ed25519PublicKeyStatus.SmallOrder;
            }
        }

        return Ed25519PublicKeyStatus.Valid;
    }

    /// <summary>
    /// Gets the reason text reported for a rejected key; shared so the build-time and runtime messages stay identical.
    /// </summary>
    public static string GetReason(Ed25519PublicKeyStatus status) => status switch
    {
        Ed25519PublicKeyStatus.InvalidLength => $"expected {PublicKeySize} bytes",
        Ed25519PublicKeyStatus.NotOnCurve => "not a valid Ed25519 public key",
        Ed25519PublicKeyStatus.SmallOrder => "small-order Ed25519 public key",
        _ => string.Empty,
    };
}
