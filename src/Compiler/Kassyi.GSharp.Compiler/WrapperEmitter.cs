using System.Globalization;
using Kassyi.GSharp.Compiler.Models;

namespace Kassyi.GSharp.Compiler;

/// <summary>Generates host-side C# wrapper classes that load and invoke GPU kernels.</summary>
internal static class WrapperEmitter
{
    private readonly struct InteropParameterInfo(
        string modifier,
        ITypeSymbol? type,
        bool isIntPtr,
        string? defaultValue = null,
        string? rawTypeName = null)
    {
        private string Modifier { get; } = modifier;
        private ITypeSymbol? Type { get; } = type;
        private bool IsIntPtr { get; } = isIntPtr;
        private string? DefaultValue { get; } = defaultValue;
        private string? RawTypeName { get; } = rawTypeName;

        public void WriteTo(SourceWriter writer, string name)
        {
            if (IsIntPtr)
            {
                writer.Append("IntPtr ");
            }
            else
            {
                if (!string.IsNullOrEmpty(Modifier))
                {
                    writer.Append(Modifier);
                    writer.AppendSpace();
                }

                if (RawTypeName != null)
                {
                    writer.Append(RawTypeName);
                    writer.AppendSpace();
                }
                else if (Type != null)
                {
                    writer.AppendFullyQualifiedCsharpName(Type);
                    writer.AppendSpace();
                }
            }

            writer.Append(name);

            if (DefaultValue == null)
            {
                return;
            }

            writer.Append(" = ");
            writer.Append(DefaultValue);
        }
    }

    private static InteropParameterInfo GetInteropParameterInfo(IParameterSymbol p, bool isDevicePtr)
    {
        string? defaultValue = null;
        if (p.HasExplicitDefaultValue)
        {
            var val = p.ExplicitDefaultValue;
            defaultValue = val switch
            {
                null => "default",
                bool b => b ? "true" : "false",
                float f => f.ToString(CultureInfo.InvariantCulture) + "f",
                double d => d.ToString(CultureInfo.InvariantCulture) + "d",
                string s => SymbolDisplay.FormatLiteral(s, true),
                _ => val.ToString()
            };
        }

        switch (isDevicePtr)
        {
            case true when (KernelLaunchEmitter.IsArrayLikeType(p.Type, out _) ||
                            p.RefKind is RefKind.Ref or RefKind.Out):
            {
                if (p.HasExplicitDefaultValue)
                {
                    defaultValue = "default";
                }

                return new InteropParameterInfo(string.Empty, null, true, defaultValue);
            }
            case true when CudaLayoutRules.IsCustomStruct(p.Type):
            {
                var tempWriter = new SourceWriter();
                tempWriter.AppendAotStructPath(p.Type);
                var rawTypeName = tempWriter.ToString();
                return new InteropParameterInfo(string.Empty, null, false, defaultValue, rawTypeName);
            }
            default:
            {
                var modifier = p.RefKind switch
                {
                    RefKind.Ref => "ref",
                    RefKind.Out => "out",
                    _ => string.Empty
                };

                return new InteropParameterInfo(modifier, p.Type, false, defaultValue);
            }
        }
    }


    public static string GenerateKernelExtensions(INamedTypeSymbol classSymbol,
        IEnumerable<(IMethodSymbol Method, string Source, string ManagedCSharpSource)> methods, GeneratorConfig config)
    {
        var className = classSymbol.Name;

        var writer = new SourceWriter();
        writer.AppendLine("""
            // <auto-generated/>
            #nullable enable
            using System;
            #pragma warning disable RS1035 // Do not use APIs banned for analyzers
            #pragma warning disable RS1016
            #pragma warning disable RS1034
            using System.Text;
            using System.Runtime.InteropServices;
            using global::Kassyi.GSharp.Core;
            using global::Kassyi.GSharp.Runtime.Interop;
            using static global::Kassyi.GSharp.Core.ManagedGpuContext;
            using global::Kassyi.ZeroAlloc.Linq;
            """);

        writer.AppendLine();

        var isGlobalNamespace = classSymbol.ContainingNamespace.IsGlobalNamespace;
        if (!isGlobalNamespace)
        {
            writer.Append("namespace ");
            writer.AppendNamespace(classSymbol.ContainingNamespace);
            writer.AppendLine();
            writer.AppendLine("{");
        }

        writer.Append("public partial class ");
        writer.AppendLine(className);
        using (writer.Scope())
        {
            writer.AppendLine("[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"Kassyi.GSharp.Compiler\", \"1.0.0.0\")]");
            writer.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
            writer.AppendLine("public static partial class AotContexts");
            using (writer.Scope())
            {
                // ReSharper disable once PossibleMultipleEnumeration
                StructMarshalingEmitter.WriteStructMarshaling(writer, methods);
            }

            // ReSharper disable once PossibleMultipleEnumeration
            foreach (var (method, source, managedCSharpSource) in methods)
            {
                WriteKernelSource(writer, method, source, config);

                if (config.TargetDialect.Equals("Cuda", StringComparison.OrdinalIgnoreCase))
                {
                    writer.AppendLine($"private static IntPtr? s_hfunc_{method.Name};");
                    WriteWarmupFunctionPointerMethod(writer, method);
                    WriteLaunchMethod(writer, method, false);
                    WriteLaunchMethod(writer, method, true);
                }
                else
                {
                    writer.AppendLine(managedCSharpSource);
                    WriteCpuDelegateDeclaration(writer, method);
                    WriteLaunchMethodCpu(writer, method);
                }
            }
        }

        if (!isGlobalNamespace)
        {
            writer.AppendLine("}");
        }

        return writer.ToString();
    }

    private static void WriteKernelSource(SourceWriter writer, IMethodSymbol method, string source,
        GeneratorConfig config)
    {
        if (!config.EmitSource)
        {
            return;
        }

        writer.Append($"public const string {method.Name}_Source = @\"");
        writer.AppendVerbatimLiteral(source);
        writer.AppendLine("\";");
        writer.AppendLine(
            $"public static readonly string {method.Name}_FullSource=" +
            $"global::Kassyi.GSharp.Generated.GSharpShared{config.TargetDialect}Prelude.Source +" +
            $"global::Kassyi.GSharp.Generated.GSharpShared{config.TargetDialect}DeviceCode.Source +" +
            $"{method.Name}_Source;");
        writer.AppendLine();
    }

    private static void WriteLaunchMethod(SourceWriter writer, IMethodSymbol method, bool isDevicePtr)
    {
        writer.AppendLine(
            "#pragma warning disable CS8500 // Takes the address of, gets the size of, or declares a pointer to a managed type");
        WriteLaunchMethodSignature(writer, method, isDevicePtr);
        using (writer.Scope())
        {
            if (!isDevicePtr)
            {
                WriteOutParameterDefaults(writer, method);
                WriteEmptyArrayGuards(writer, method);
            }

            WriteAutoResultAllocation(writer, method);

            writer.AppendLine(
                "using (var _cudaCtxScope = new global::Kassyi.GSharp.Runtime.Aot.GpuKernelLoader.CudaContextScope())");
            using (writer.Scope())
            {
                WriteCudaKernelCompilationCall(writer, method);
                KernelLaunchEmitter.WriteVariablesInitialization(writer, method, isDevicePtr);

                writer.AppendLine("try");
                using (writer.Scope())
                {
                    KernelLaunchEmitter.WriteMarshalAndLaunchKernel(writer, method, isDevicePtr);
                }

                writer.AppendLine("finally");
                using (writer.Scope())
                {
                    KernelLaunchEmitter.WriteCleanup(writer, method, isDevicePtr);
                }
            }

            WriteAutoResultReturn(writer, method);
        }

        writer.AppendLine("#pragma warning restore CS8500");
    }

    private static void WriteLaunchMethodCpu(SourceWriter writer, IMethodSymbol method)
    {
        writer.AppendLine("#pragma warning disable CS8500");
        WriteLaunchMethodSignature(writer, method, false);
        using (writer.Scope())
        {
            WriteOutParameterDefaults(writer, method);
            WriteEmptyArrayGuards(writer, method);
            WriteAutoResultAllocation(writer, method);
            WriteManagedExecutionFallback(writer, method);
            WriteCpuDelegateGetOrCompile(writer, method);
            WriteCpuFixedBlocksAndInvoke(writer, method);
        }

        writer.AppendLine("#pragma warning restore CS8500");
    }

    private static void WriteLaunchMethodSignature(SourceWriter writer, IMethodSymbol method, bool isDevicePtr)
    {
        writer.AppendLine("[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"Kassyi.GSharp.Compiler\", \"1.0.0.0\")]");
        writer.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.Append("public static unsafe ");
        if (method.ReturnType.SpecialType != SpecialType.System_Void)
        {
            writer.AppendFullyQualifiedCsharpName(method.ReturnType);
            writer.Append("[] ");
        }
        else
        {
            writer.Append("void ");
        }


        writer.Append("Launch");
        writer.Append(method.Name);
        if (isDevicePtr)
        {
            writer.Append("Ptr");
        }

        using (writer.Parentheses())
        {
            var isFirst = true;
            foreach (var p in method.Parameters)
            {
                if (!isFirst)
                {
                    writer.AppendComma();
                    writer.AppendSpace();
                }

                var info = GetInteropParameterInfo(p, isDevicePtr);
                info.WriteTo(writer, p.Name);

                isFirst = false;
            }

            if (!isFirst)
            {
                writer.AppendComma();
                writer.AppendSpace();
            }

            writer.Append(
                "uint gridDimX = 1, uint gridDimY = 1, uint gridDimZ = 1, uint blockDimX = 1, uint blockDimY = 1," +
                "uint blockDimZ = 1, uint sharedMemBytes = 0, IntPtr hStream = default, " +
                "System.ReadOnlySpan<System.Collections.Generic.KeyValuePair<string, string>> macros = default");
        }

        writer.AppendLine();
    }

    private static void WriteOutParameterDefaults(SourceWriter writer, IMethodSymbol method)
    {
        foreach (var p in method.Parameters)
        {
            if (p.RefKind is not RefKind.Out || KernelLaunchEmitter.IsArrayLikeType(p.Type, out _))
            {
                continue;
            }

            writer.Append(p.Name);
            writer.AppendLine(" = default;");
        }
    }

    private static void WriteEmptyArrayGuards(SourceWriter writer, IMethodSymbol method)
    {
        var hasArray = false;
        foreach (var p in method.Parameters)
        {
            if (!KernelLaunchEmitter.IsArrayLikeType(p.Type, out _))
            {
                continue;
            }

            hasArray = true;
            break;
        }

        if (!hasArray)
        {
            return;
        }

        writer.Append("if ");
        using (writer.Parentheses())
        {
            var isFirst = true;
            foreach (var p in method.Parameters)
            {
                if (!KernelLaunchEmitter.IsArrayLikeType(p.Type, out _))
                {
                    continue;
                }

                if (!isFirst)
                {
                    writer.Append(" || ");
                }

                writer.Append(p.Name);
                writer.Append(".Length == 0");
                isFirst = false;
            }
        }

        using (writer.Scope())
        {
            if (method.ReturnType.SpecialType != SpecialType.System_Void)
            {
                writer.Append("return System.Array.Empty<");
                writer.AppendFullyQualifiedCsharpName(method.ReturnType);
                writer.AppendLine(">();");
            }
            else
            {
                writer.AppendLine("return;");
            }
        }

        writer.AppendLine();
    }


    private static string GetMangledKernelName(IMethodSymbol method) =>
        $"{method.ContainingType.Name}_{method.Name}";

    private static void WriteWarmupFunctionPointerMethod(SourceWriter writer, IMethodSymbol method)
    {
        var mangledName = GetMangledKernelName(method);
        writer.AppendLine(
            "/// <summary>Preloads the CUDA module and resolves the function pointer for this kernel.</summary>");
        writer.AppendLine($"public static void WarmupFunctionPointer{method.Name}()");
        using (writer.Scope())
        {
            writer.AppendLine($"if (s_hfunc_{method.Name}.HasValue) return;");
            writer.Append("IntPtr hModule = global::Kassyi.GSharp.Generated.GSharpModuleContext_");
            var assemblyName = IdentifierHelper.ToSafeIdentifier(method.ContainingAssembly.Name);
            writer.Append(assemblyName);
            writer.AppendLine(".GetOrLoadModule();");
            writer.AppendLine(
                $"s_hfunc_{method.Name} = global::Kassyi.GSharp.Runtime.Aot.GpuKernelLoader.GetFunction(hModule, \"{mangledName}\");");
        }

        writer.AppendLine();
    }

    private static void WriteCudaKernelCompilationCall(SourceWriter writer, IMethodSymbol method)
    {
        writer.AppendLine($"WarmupFunctionPointer{method.Name}();");
        writer.AppendLine($"IntPtr hfunc = s_hfunc_{method.Name}!.Value;");
        writer.AppendLine();
    }

    public static string GenerateModuleContextClass(string assemblyName,
        IEnumerable<TranspiledKernelResult> kernelMethods)
    {
        var safeAssemblyName = IdentifierHelper.ToSafeIdentifier(assemblyName);

        var writer = new SourceWriter();
        writer.AppendLine($$"""
            // <auto-generated/>
            #nullable enable
            using System;
            using System.Threading;

            namespace Kassyi.GSharp.Generated
            {
            [global::System.CodeDom.Compiler.GeneratedCodeAttribute("Kassyi.GSharp.Compiler", "1.0.0.0")]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            public static class GSharpModuleContext_{{safeAssemblyName}}
            {
            private static IntPtr? s_hModule;
            private static readonly object s_lock = new object();

            /// <summary>
            /// Loads the fatbin module for this assembly into the CUDA driver if it hasn't been loaded yet.
            /// </summary>
            public static IntPtr GetOrLoadModule()
            {
            if (s_hModule.HasValue) return s_hModule.Value;
            lock (s_lock)
            {
            if (s_hModule.HasValue) return s_hModule.Value;

            var baseDir = System.IO.Path.GetDirectoryName(typeof(GSharpModuleContext_{{safeAssemblyName}}).Assembly.Location) ??
                System.AppContext.BaseDirectory;
            var fatbinPath = System.IO.Path.Combine(baseDir, "Kassyi.GSharp.Kernels_{{safeAssemblyName}}.gfatbin");
            if (!System.IO.File.Exists(fatbinPath))
            {
            throw new System.InvalidOperationException($"AOT kernel binary was not found at '{fatbinPath}'.");
            }

            byte[] binaryData = System.IO.File.ReadAllBytes(fatbinPath);
            s_hModule = global::Kassyi.GSharp.Runtime.Aot.GpuKernelLoader.LoadModule(binaryData);
            return s_hModule.Value;
            }
            }

            /// <summary>
            /// Preloads the module and all function pointers for kernels in this assembly to eliminate lazy-loading latency.
            /// </summary>
            public static void Warmup()
            {
            // Force load the module first
            GetOrLoadModule();
            """);

        foreach (var methodResult in kernelMethods)
        {
            var method = methodResult.MethodSymbol;
            writer.Append("global::");
            writer.AppendNamespace(method.ContainingNamespace);
            if (!method.ContainingNamespace.IsGlobalNamespace)
            {
                writer.Append('.');
            }
            writer.Append(method.ContainingType.Name);
            writer.AppendLine($".WarmupFunctionPointer{method.Name}();");
        }

        writer.AppendLine("}}}");

        return writer.ToString();
    }

    private static void WriteCpuDelegateDeclaration(SourceWriter writer, IMethodSymbol method)
    {
        // Generate Delegate
        writer.AppendLine(
            "[System.Runtime.InteropServices.UnmanagedFunctionPointer(System.Runtime.InteropServices.CallingConvention.Cdecl)]");
        writer.Append("private unsafe delegate void ");
        writer.Append(method.Name);
        writer.Append("_Delegate");
        using (writer.Parentheses())
        {
            writer.Append(
                "uint gridDimX, uint gridDimY, uint gridDimZ, uint blockDimX, uint blockDimY, uint blockDimZ");
            foreach (var p in method.Parameters)
            {
                if (p.HasAttribute(KnownAttributes.Constant))
                {
                    continue;
                }

                writer.AppendComma();
                writer.AppendSpace();

                if (KernelLaunchEmitter.IsArrayLikeType(p.Type, out _))
                {
                    writer.Append("global::Kassyi.GSharp.Runtime.Interop.GSharpArrayProxy ");
                    writer.Append(p.Name);
                }
                else
                {
                    writer.AppendFullyQualifiedCsharpName(p.Type);
                    if (p.RefKind is RefKind.Ref or RefKind.Out)
                    {
                        writer.Append("*");
                    }

                    writer.AppendSpace();
                    writer.Append(p.Name);
                }
            }

            if (method.ReturnType.SpecialType != SpecialType.System_Void)
            {
                writer.AppendComma();
                writer.AppendSpace();
                writer.AppendFullyQualifiedCsharpName(method.ReturnType);
                writer.Append("* __gsharp_auto_result");
            }
        }

        writer.AppendLine(";");
        writer.AppendLine();
    }

    private static void WriteManagedExecutionFallback(SourceWriter writer, IMethodSymbol method)
    {
        var safeAssemblyName = IdentifierHelper.ToSafeIdentifier(method.ContainingAssembly.Name);
        var mangledName = GetMangledKernelName(method);

        writer.AppendLine(
            "var archSuffix = System.Runtime.InteropServices.RuntimeInformation.ProcessArchitecture ==" +
            " System.Runtime.InteropServices.Architecture.Arm64 ? \"_arm64\" : \"_x64\";");
        writer.AppendLine(
            $"var dllName = $\"Kassyi.GSharp.Kernels_{safeAssemblyName}{{archSuffix}}.dll\";");
        writer.AppendLine(
            "var dllPath = System.IO.Path.Combine(System.AppContext.BaseDirectory, dllName);");

        writer.AppendLine(
            "if (global::Kassyi.GSharp.Runtime.Aot.CpuKernelLoader.ShouldUseManagedExecution(dllPath))");
        using (writer.Scope())
        {
            writer.AppendLine("int _gsharp_total_blocks = (int)(gridDimX * gridDimY * gridDimZ);");
            writer.AppendLine("int _gsharp_threads_per_block = (int)(blockDimX * blockDimY * blockDimZ);");
            writer.AppendLine(
                $"var _gsharp_contexts = new __gsharp_context_{mangledName}[_gsharp_total_blocks * _gsharp_threads_per_block];");
            writer.AppendLine("for (int i = 0; i < _gsharp_contexts.Length; i++) {");
            writer.AppendLine($"  _gsharp_contexts[i] = new __gsharp_context_{mangledName}();");
            writer.AppendLine("}");

            writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.InitializeGrid(_gsharp_total_blocks);");

            writer.AppendLine("bool anyGridActive = true;");
            writer.AppendLine("while (anyGridActive)");
            using (writer.Scope())
            {
                writer.AppendLine("anyGridActive = false;");
                writer.AppendLine("for (int _b_idx = 0; _b_idx < _gsharp_total_blocks; _b_idx++)");
                using (writer.Scope())
                {
                    writer.AppendLine("int bx = _b_idx % (int)gridDimX;");
                    writer.AppendLine("int by = (_b_idx / (int)gridDimX) % (int)gridDimY;");
                    writer.AppendLine("int bz = _b_idx / (int)(gridDimX * gridDimY);");

                    writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.IsActive = true;");
                    writer.AppendLine("try");
                    using (writer.Scope())
                    {
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.BlockIdxX = bx;");
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.BlockIdxY = by;");
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.BlockIdxZ = bz;");
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.BlockDimX = (int)blockDimX;");
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.BlockDimY = (int)blockDimY;");
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.BlockDimZ = (int)blockDimZ;");
                    writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.GridDimX = (int)gridDimX;");
                    writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.GridDimY = (int)gridDimY;");
                    writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.GridDimZ = (int)gridDimZ;");

                    writer.AppendLine("bool anyBlockActive = true;");
                    writer.AppendLine("while (anyBlockActive)");
                    using (writer.Scope())
                    {
                        writer.AppendLine("anyBlockActive = false;");
                        writer.AppendLine("bool gridSyncRequested = false;");
                        writer.AppendLine("for (int _t_idx = 0; _t_idx < _gsharp_threads_per_block; _t_idx++)");
                        using (writer.Scope())
                        {
                            writer.AppendLine("int tx = _t_idx % (int)blockDimX;");
                            writer.AppendLine("int ty = (_t_idx / (int)blockDimX) % (int)blockDimY;");
                            writer.AppendLine("int tz = _t_idx / (int)(blockDimX * blockDimY);");
                            writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.ThreadIdxX = tx;");
                            writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.ThreadIdxY = ty;");
                            writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.ThreadIdxZ = tz;");

                            writer.AppendLine("int linear_tid = _b_idx * _gsharp_threads_per_block + _t_idx;");
                            writer.AppendLine("if (_gsharp_contexts[linear_tid]._state != -1)");
                            using (writer.Scope())
                            {
                                writer.AppendLine("anyGridActive = true;");
                                writer.AppendLine("anyBlockActive = true;");
                                writer.AppendLine("_gsharp_contexts[linear_tid]._yieldedForGridSync = false;");
                                writer.AppendLine(
                                    "global::Kassyi.GSharp.Core.ManagedGpuContext.ResetAllocationIndex();");

                                writer.Append($"__gsharp_statemachine_{mangledName}(");
                                bool isFirst = true;
                                foreach (var p in method.Parameters)
                                {
                                    if (!isFirst)
                                    {
                                        writer.Append(", ");
                                    }

                                    isFirst = false;
                                    if (p.RefKind == RefKind.Ref)
                                    {
                                        writer.Append("ref ");
                                    }
                                    else if (p.RefKind == RefKind.Out)
                                    {
                                        writer.Append("out ");
                                    }

                                    writer.Append(p.Name);
                                }

                                if (!isFirst)
                                {
                                    writer.Append(", ");
                                }

                                writer.Append("_gsharp_contexts[linear_tid]");
                                if (method.ReturnType.SpecialType != SpecialType.System_Void)
                                {
                                    writer.Append(", ref __gsharp_auto_result[linear_tid]");
                                }

                                writer.AppendLine(");");

                                writer.AppendLine("if (_gsharp_contexts[linear_tid]._yieldedForGridSync)");
                                using (writer.Scope())
                                {
                                    writer.AppendLine("gridSyncRequested = true;");
                                }
                            }
                        }

                        writer.AppendLine("if (gridSyncRequested)");
                        using (writer.Scope())
                        {
                            writer.AppendLine("break;");
                        }
                    }

                    }
                    writer.AppendLine("finally");
                    using (writer.Scope())
                    {
                        writer.AppendLine("global::Kassyi.GSharp.Core.ManagedGpuContext.IsActive = false;");
                    }
                }
            }

            WriteAutoResultReturn(writer, method);
            if (method.ReturnType.SpecialType == SpecialType.System_Void)
            {
                writer.AppendLine("return;");
            }
        }
    }

    private static void WriteCpuDelegateGetOrCompile(SourceWriter writer, IMethodSymbol method)
    {
        var mangledName = GetMangledKernelName(method);

        writer.AppendLine(
            $"var hfunc = global::Kassyi.GSharp.Runtime.Aot.CpuKernelLoader.LoadAotKernel<{method.Name}_Delegate>(\"__gsharp_launch_{mangledName}\", dllPath);");
    }

    private static void WriteCpuFixedBlocksAndInvoke(SourceWriter writer, IMethodSymbol method)
    {
        var hasFixed = false;

        foreach (var p in method.Parameters)
        {
            if (KernelLaunchEmitter.IsArrayLikeType(p.Type, out var elementType))
            {
                writer.Append("fixed (");
                writer.AppendFullyQualifiedCsharpName(elementType);
                writer.AppendLine($"* p_{p.Name} = {p.Name})");
                hasFixed = true;
            }
            else if (p.RefKind is RefKind.Ref or RefKind.Out)
            {
                writer.Append("fixed (");
                writer.AppendFullyQualifiedCsharpName(p.Type);
                writer.AppendLine($"* p_{p.Name} = &{p.Name})");
                hasFixed = true;
            }
        }

        if (method.ReturnType.SpecialType != SpecialType.System_Void)
        {
            writer.Append("fixed (");
            writer.AppendFullyQualifiedCsharpName(method.ReturnType);
            writer.AppendLine("* p___gsharp_auto_result = __gsharp_auto_result)");
            hasFixed = true;
        }

        if (hasFixed)
        {
            using (writer.Scope())
            {
                WriteDelegateInvocation(writer, method);
            }
        }
        else
        {
            WriteDelegateInvocation(writer, method);
        }

        WriteAutoResultReturn(writer, method);
    }

    private static void WriteDelegateInvocation(SourceWriter writer, IMethodSymbol method)
    {
        writer.Append("hfunc");
        using (writer.Parentheses())
        {
            writer.Append("gridDimX, gridDimY, gridDimZ, blockDimX, blockDimY, blockDimZ");

            foreach (var p in method.Parameters)
            {
                if (p.HasAttribute(KnownAttributes.Constant))
                {
                    continue;
                }

                writer.AppendComma();
                writer.AppendSpace();

                if (KernelLaunchEmitter.IsArrayLikeType(p.Type, out _))
                {
                    writer.Append(
                        $"new global::Kassyi.GSharp.Runtime.Interop.GSharpArrayProxy {{ Data = (IntPtr)p_{p.Name}, Length = {p.Name}.Length }}");
                }
                else if (p.RefKind is RefKind.Ref or RefKind.Out)
                {
                    writer.Append("p_");
                    writer.Append(p.Name);
                }
                else
                {
                    writer.Append(p.Name);
                }
            }

            if (method.ReturnType.SpecialType != SpecialType.System_Void)
            {
                writer.AppendComma();
                writer.AppendSpace();
                writer.Append("p___gsharp_auto_result");
            }
        }

        writer.AppendLine(";");
        writer.AppendLine("global::Kassyi.GSharp.Runtime.Aot.CpuKernelLoader.ThrowIfNativeError(dllPath);");
    }

    private static void WriteAutoResultAllocation(SourceWriter writer, IMethodSymbol method)
    {
        if (method.ReturnType.SpecialType != SpecialType.System_Void)
        {
            writer.AppendLine(
                "if (gridDimX == 0 || gridDimY == 0 || gridDimZ == 0 || blockDimX == 0 || blockDimY == 0 || blockDimZ == 0)" +
                " throw new global::System.ArgumentOutOfRangeException(\"Dimensions\", \"Launch dimensions must be greater than 0.\");");
            writer.AppendLine(
                "uint __gsharp_total_threads; checked { __gsharp_total_threads = (gridDimX * gridDimY * gridDimZ) * (blockDimX * blockDimY * blockDimZ); }");
            writer.Append("var __gsharp_auto_result = new ");
            writer.AppendFullyQualifiedCsharpName(method.ReturnType);
            writer.AppendLine("[__gsharp_total_threads];");
        }
    }

    private static void WriteAutoResultReturn(SourceWriter writer, IMethodSymbol method)
    {
        if (method.ReturnType.SpecialType != SpecialType.System_Void)
        {
            writer.AppendLine("return __gsharp_auto_result;");
        }
    }
