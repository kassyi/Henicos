namespace Kassyi.GSharp.Compiler;

/// <summary>Generates host-side C# wrapper classes that JIT-compile and invoke GPU kernels.</summary>
/// <remarks><para>Implements: <b>GEN-35</b></para></remarks>
internal static class WrapperEmitter
{
    public static string GenerateWrapperClass(IMethodSymbol method, string source, string targetDialect)
    {
        var className = method.ContainingType.Name + "Wrapper";
        var namespaceName = method.ContainingNamespace.IsGlobalNamespace
            ? "Kassyi.GSharp.Generated"
            : method.ContainingNamespace.ToDisplayString();

        var writer = new SourceWriter();
        writer.AppendLine("""
            // <auto-generated/>
            #nullable enable
            using System;
            using System.Runtime.InteropServices;
            using global::Kassyi.GSharp.Core;
            using global::Kassyi.GSharp.Runtime.Interop;
            """);

        writer.AppendLine();
        writer.Append("namespace ");
        writer.AppendLine(namespaceName);
        using (writer.Scope())
        {
            writer.Append("public static partial class ");
            writer.AppendLine(className);
            using (writer.Scope())
            {
                if (method.Parameters.Any(p => p.HasAttribute(KnownAttributes.JitConstant)))
                {
                    writer.AppendLine("[System.ThreadStatic]");
                    writer.Append("private static global::Kassyi.GSharp.Runtime.Jit.JitConstantArg[]? __t_jitConstants_array_");
                    writer.Append(method.Name);
                    writer.AppendLine(";");
                    writer.AppendLine();
                }

                WriteKernelSource(writer, method, source, targetDialect);
                MarshalingEmitter.WriteStructMarshaling(writer, method);

                if (targetDialect.Equals("Cuda", StringComparison.OrdinalIgnoreCase))
                {
                    WriteLaunchMethod(writer, method, false, targetDialect);
                    WriteLaunchMethod(writer, method, true, targetDialect);
                }
                else
                {
                    WriteLaunchMethodCpu(writer, method, targetDialect);
                }
            }
        }

        return writer.ToString();
    }

    private static void WriteKernelSource(SourceWriter writer, IMethodSymbol method, string source, string targetDialect)
    {
        var escapedSource = source.Replace("\"", "\"\"");
        writer.Append("public const string ");
        writer.Append(method.Name);
        writer.Append("_Source = @\"");
        writer.Append(escapedSource);
        writer.AppendLine("\";");
        
        writer.Append("public static readonly string ");
        writer.Append(method.Name);
        writer.Append("_FullSource = global::Kassyi.GSharp.Generated.GSharpShared");
        writer.Append(targetDialect);
        writer.Append("Code.Source + ");
        writer.Append(method.Name);
        writer.AppendLine("_Source;");
        writer.AppendLine();
    }

    private static void WriteLaunchMethod(SourceWriter writer, IMethodSymbol method, bool isDevicePtr,
        string targetDialect)
    {
        writer.AppendLine(
            "#pragma warning disable CS8500 // Takes the address of, gets the size of, or declares a pointer to a managed type");
        WriteLaunchMethodSignature(writer, method, isDevicePtr);
        using (writer.Scope())
        {
            if (!isDevicePtr)
            {
                foreach (var p in method.Parameters)
                {
                    if (p.RefKind is RefKind.Out && p.Type is not IArrayTypeSymbol)
                    {
                        writer.Append(p.Name);
                        writer.AppendLine(" = default;");
                    }
                }

                bool hasArray = false;
                foreach (var p in method.Parameters)
                {
                    if (p.Type is IArrayTypeSymbol)
                    {
                        hasArray = true;
                        break;
                    }
                }

                if (hasArray)
                {
                    writer.Append("if ");
                    using (writer.Parentheses())
                    {
                        bool isFirst = true;
                        foreach (var p in method.Parameters)
                        {
                            if (p.Type is IArrayTypeSymbol)
                            {
                                if (!isFirst)
                                {
                                    writer.Append(" || ");
                                }

                                writer.Append(p.Name);
                                writer.Append(".Length == 0");
                                isFirst = false;
                            }
                        }
                    }

                    using (writer.Scope())
                    {
                        writer.AppendLine("return;");
                    }

                    writer.AppendLine();
                }
            }

            writer.AppendLine(
                "using (var _cudaCtxScope = new global::Kassyi.GSharp.Runtime.Jit.JitEngine.CudaContextScope())");
            using (writer.Scope())
            {
                WriteKernelCompilationCall(writer, method, targetDialect);
                MarshalingEmitter.WriteVariablesInitialization(writer, method, isDevicePtr);

                writer.AppendLine("try");
                using (writer.Scope())
                {
                    MarshalingEmitter.WriteMarshalAndLaunchKernel(writer, method, isDevicePtr);
                }

                writer.AppendLine("finally");
                using (writer.Scope())
                {
                    MarshalingEmitter.WriteCleanup(writer, method, isDevicePtr);
                }
            }
        }

        writer.AppendLine("#pragma warning restore CS8500");
    }

    private static void WriteLaunchMethodSignature(SourceWriter writer, IMethodSymbol method, bool isDevicePtr)
    {
        writer.Append("public static unsafe void Launch_");
        writer.Append(method.Name);
        if (isDevicePtr)
        {
            writer.Append("_Device");
        }

        using (writer.Parentheses())
        {
            var first = true;
            foreach (var p in method.Parameters)
            {
                if (!first)
                {
                    writer.AppendComma();
                    writer.AppendSpace();
                }

                if (isDevicePtr && (p.Type is IArrayTypeSymbol || p.RefKind is RefKind.Ref or RefKind.Out))
                {
                    writer.Append("IntPtr ");
                    writer.Append(p.Name);
                }
                else
                {
                    if (p.RefKind == RefKind.Ref)
                    {
                        writer.Append("ref ");
                    }
                    else if (p.RefKind == RefKind.Out)
                    {
                        writer.Append("out ");
                    }

                    writer.Append(p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                    writer.AppendSpace();
                    writer.Append(p.Name);
                }

                first = false;
            }

            if (!first)
            {
                writer.AppendComma();
                writer.AppendSpace();
            }

            writer.Append(
                "uint gridDimX = 1, uint gridDimY = 1, uint gridDimZ = 1, uint blockDimX = 1, uint blockDimY = 1, uint blockDimZ = 1, uint sharedMemBytes = 0, System.ReadOnlySpan<System.Collections.Generic.KeyValuePair<string, string>> macros = default");
        }

        writer.AppendLine();
    }

    private static void WriteKernelCompilationCall(SourceWriter writer, IMethodSymbol method, string targetDialect)
    {
        int jitConstantCount = 0;
        foreach (var p in method.Parameters)
        {
            if (p.HasAttribute(KnownAttributes.JitConstant))
            {
                jitConstantCount++;
            }
        }

        if (jitConstantCount > 0)
        {
            writer.AppendLine($"__t_jitConstants_array_{method.Name} ??= new global::Kassyi.GSharp.Runtime.Jit.JitConstantArg[{jitConstantCount}];");

            int index = 0;
            foreach (var p in method.Parameters)
            {
                if (p.HasAttribute(KnownAttributes.JitConstant))
                {
                    writer.AppendLine($"__t_jitConstants_array_{method.Name}[{index}] = global::Kassyi.GSharp.Runtime.Jit.JitConstantArg.Create(\"{p.Name}\", {p.Name});");
                    index++;
                }
            }
            writer.AppendLine($"System.ReadOnlySpan<global::Kassyi.GSharp.Runtime.Jit.JitConstantArg> __t_jitConstants = new System.ReadOnlySpan<global::Kassyi.GSharp.Runtime.Jit.JitConstantArg>(__t_jitConstants_array_{method.Name}, 0, {jitConstantCount});");
        }
        else
        {
            writer.AppendLine("System.ReadOnlySpan<global::Kassyi.GSharp.Runtime.Jit.JitConstantArg> __t_jitConstants = default;");
        }

        writer.Append("IntPtr hfunc = global::Kassyi.GSharp.Runtime.Jit.JitEngine.GetOrCompileKernel");
        using (writer.Parentheses())
        {
            writer.Append("\"");
            writer.Append(method.Name);
            writer.Append("\", ");
            writer.Append(method.Name);
            writer.Append("_FullSource, __t_jitConstants, macros");
        }

        writer.AppendLine(";");
        writer.AppendLine();
    }

    private static void WriteLaunchMethodCpu(SourceWriter writer, IMethodSymbol method, string targetDialect)
    {
        writer.AppendLine("#pragma warning disable CS8500");

        // Generate Delegate
        writer.AppendLine(
            "[System.Runtime.InteropServices.UnmanagedFunctionPointer(System.Runtime.InteropServices.CallingConvention.Cdecl)]");
        writer.Append("private unsafe delegate void ");
        writer.Append(method.Name);
        writer.Append("_Delegate");
        using (writer.Parentheses())
        {
            writer.Append(
                "uint gridDimX, uint gridDimY, uint gridDimZ, uint blockDimX, uint blockDimY, uint blockDimZ");
            foreach (var p in method.Parameters)
            {
                if (p.HasAttribute(KnownAttributes.JitConstant))
                {
                    continue;
                }

                writer.AppendComma();
                writer.AppendSpace();

                if (p.Type is IArrayTypeSymbol arrayType)
                {
                    writer.Append(arrayType.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                    writer.Append("* ");
                    writer.Append(p.Name);
                }
                else
                {
                    writer.Append(p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                    if (p.RefKind is RefKind.Ref or RefKind.Out)
                    {
                        writer.Append("*");
                    }

                    writer.AppendSpace();
                    writer.Append(p.Name);
                }
            }
        }

        writer.AppendLine(";");
        writer.AppendLine();

        WriteLaunchMethodSignature(writer, method, false);
        using (writer.Scope())
        {
            // Null array checks
            foreach (var p in method.Parameters)
            {
                if (p.RefKind is RefKind.Out && p.Type is not IArrayTypeSymbol)
                {
                    writer.Append(p.Name);
                    writer.AppendLine(" = default;");
                }
            }

            bool hasArray = false;
            foreach (var p in method.Parameters)
            {
                if (p.Type is IArrayTypeSymbol)
                {
                    hasArray = true;
                    break;
                }
            }

            if (hasArray)
            {
                writer.Append("if ");
                using (writer.Parentheses())
                {
                    bool isFirst = true;
                    foreach (var p in method.Parameters)
                    {
                        if (p.Type is IArrayTypeSymbol)
                        {
                            if (!isFirst)
                            {
                                writer.Append(" || ");
                            }

                            writer.Append(p.Name);
                            writer.Append(".Length == 0");
                            isFirst = false;
                        }
                    }
                }

                using (writer.Scope())
                {
                    writer.AppendLine("return;");
                }

                writer.AppendLine();
            }

            // JIT constants
            int jitConstantCount = 0;
            foreach (var p in method.Parameters)
            {
                if (p.HasAttribute(KnownAttributes.JitConstant))
                {
                    jitConstantCount++;
                }
            }

            if (jitConstantCount > 0)
            {
                writer.AppendLine($"__t_jitConstants_array_{method.Name} ??= new global::Kassyi.GSharp.Runtime.Jit.JitConstantArg[{jitConstantCount}];");

                int index = 0;
                foreach (var p in method.Parameters)
                {
                    if (p.HasAttribute(KnownAttributes.JitConstant))
                    {
                        writer.AppendLine($"__t_jitConstants_array_{method.Name}[{index}] = global::Kassyi.GSharp.Runtime.Jit.JitConstantArg.Create(\"{p.Name}\", {p.Name});");
                        index++;
                    }
                }
                writer.AppendLine($"System.ReadOnlySpan<global::Kassyi.GSharp.Runtime.Jit.JitConstantArg> __t_jitConstants = new System.ReadOnlySpan<global::Kassyi.GSharp.Runtime.Jit.JitConstantArg>(__t_jitConstants_array_{method.Name}, 0, {jitConstantCount});");
            }
            else
            {
                writer.AppendLine("System.ReadOnlySpan<global::Kassyi.GSharp.Runtime.Jit.JitConstantArg> __t_jitConstants = default;");
            }

            // Get Delegate
            writer.Append(
                "        var hfunc = global::Kassyi.GSharp.Runtime.Jit.CpuJitEngine.GetOrCompileKernel<");
            writer.Append(method.Name);
            writer.Append("_Delegate>(\"__gsharp_launch_");
            writer.Append(method.Name);
            writer.Append("\", ");
            writer.Append(method.Name);
            writer.Append("_FullSource, __t_jitConstants, macros);");
            writer.AppendLine();

            // Generate fixed blocks
            bool hasFixed = false;
            foreach (var p in method.Parameters)
            {
                if (p.Type is IArrayTypeSymbol || (p.RefKind is RefKind.Ref or RefKind.Out && p.Type is not IArrayTypeSymbol))
                {
                    hasFixed = true;
                    break;
                }
            }

            if (hasFixed)
            {
                foreach (var p in method.Parameters)
                {
                    if (p.Type is IArrayTypeSymbol arrayType)
                    {
                        writer.Append("fixed (");
                        writer.Append(
                            arrayType.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                        writer.Append("* p_");
                        writer.Append(p.Name);
                        writer.Append(" = ");
                        writer.Append(p.Name);
                        writer.AppendLine(")");
                    }
                }

                foreach (var p in method.Parameters)
                {
                    if (p.RefKind is RefKind.Ref or RefKind.Out && p.Type is not IArrayTypeSymbol)
                    {
                        writer.Append("fixed (");
                        writer.Append(p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                        writer.Append("* p_");
                        writer.Append(p.Name);
                        writer.Append(" = &");
                        writer.Append(p.Name);
                        writer.AppendLine(")");
                    }
                }

                using (writer.Scope())
                {
                    WriteDelegateInvocation(writer, method);
                }
            }
            else
            {
                WriteDelegateInvocation(writer, method);
            }
        }

        writer.AppendLine("#pragma warning restore CS8500");
    }

    private static void WriteDelegateInvocation(SourceWriter writer, IMethodSymbol method)
    {
        writer.Append("hfunc");
        using (writer.Parentheses())
        {
            writer.Append("gridDimX, gridDimY, gridDimZ, blockDimX, blockDimY, blockDimZ");

            foreach (var p in method.Parameters)
            {
                if (p.HasAttribute(KnownAttributes.JitConstant))
                {
                    continue;
                }

                writer.AppendComma();
                writer.AppendSpace();

                if (p.Type is IArrayTypeSymbol || p.RefKind is RefKind.Ref or RefKind.Out)
                {
                    writer.Append("p_");
                    writer.Append(p.Name);
                }
                else
                {
                    writer.Append(p.Name);
                }
            }
        }

        writer.AppendLine(";");
    }
}
