namespace Kassyi.GSharp.Compiler.NativeApi;

/// <summary>
/// Produces C# sources from <see cref="NativeApiDefinition"/> models. Free of I/O so that both the build-time
/// <c>native-api</c> tool and the <c>NativeApiGenerator</c> source generator share identical output.
/// </summary>
internal static class NativeApiEmitter
{
    public const string ResolverClassName = "GSharpNativeLibraryResolver";

    /// <summary>
    /// Emits P/Invoke bindings for a <see cref="NativeApiBindingKind.Library"/> definition.
    /// </summary>
    /// <param name="def">The definition.</param>
    /// <param name="useDllImport">
    /// <see langword="true"/> to emit self-contained <c>extern</c> <c>[DllImport]</c> methods. Required when the
    /// output is produced by a source generator, because the <c>LibraryImport</c> generator never sees other
    /// generators' output and the <c>partial</c> declarations would stay unimplemented. <see langword="false"/>
    /// emits <c>[LibraryImport]</c> partials for sources added to the compilation by the build-time tool.
    /// </param>
    public static string EmitLibraryBindings(NativeApiDefinition def, bool useDllImport = false)
    {
        if (useDllImport)
        {
            return EmitDllImportBindings(def);
        }

        using var writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line("using System.Runtime.CompilerServices;");
        writer.Line("using System.Runtime.InteropServices;");
        writer.Line();
        writer.Line($"namespace {def.Namespace};");
        writer.Line();

        writer.Line("// ReSharper disable InconsistentNaming");
        writer.Line("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.Line($"public static partial class {def.ClassName}");
        using (writer.Scope())
        {
            foreach (var m in def.Methods)
            {
                EmitDocumentation(writer, m);

                writer.Append("[LibraryImport(");
                ModuleKernelLaunchEmitter.AppendStringLiteral(writer, def.LibraryName ?? string.Empty);
                if (!string.IsNullOrEmpty(m.EntryPoint))
                {
                    writer.Append(", EntryPoint = ");
                    ModuleKernelLaunchEmitter.AppendStringLiteral(writer, m.EntryPoint ?? string.Empty);
                }

                if (!string.IsNullOrEmpty(m.StringMarshalling))
                {
                    writer.Append($", StringMarshalling = StringMarshalling.{m.StringMarshalling}");
                }

                writer.AppendLine(")]");
                writer.Line("[UnmanagedCallConv(CallConvs = [typeof(CallConvStdcall)])]");

                var unsafeMod = m.IsUnsafe ? "unsafe " : "";
                writer.Append($"public static {unsafeMod}partial {m.ReturnType} {m.Name}");
                using (writer.Parentheses())
                {
                    for (var i = 0; i < m.Parameters.Length; i++)
                    {
                        var p = m.Parameters[i];
                        if (i > 0)
                        {
                            writer.Append(", ");
                        }

                        writer.Append($"{p.Type} {p.Name}");
                    }
                }

                writer.AppendLine(";");
                writer.Line();
            }
        }

        return writer.ToString();
    }

    private static string EmitDllImportBindings(NativeApiDefinition def)
    {
        using var writer = new SourceWriter();
        writer.AppendLine("// <auto-generated/>");
        writer.AppendLine("#nullable enable");
        writer.AppendLine("using System;");
        writer.AppendLine("using System.Runtime.InteropServices;");
        writer.AppendLine();
        writer.AppendLine($"namespace {def.Namespace};");
        writer.AppendLine();
        writer.AppendLine("// ReSharper disable InconsistentNaming");
        writer.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.AppendLine($"public static partial class {def.ClassName}");
        using (writer.Scope())
        {
            foreach (var m in def.Methods)
            {
                EmitDocumentation(writer, m);

                var isUtf8 = m.StringMarshalling == "Utf8";
                writer.Append("[DllImport(");
                ModuleKernelLaunchEmitter.AppendStringLiteral(writer, def.LibraryName ?? string.Empty);
                writer.Append(", EntryPoint = ");
                ModuleKernelLaunchEmitter.AppendStringLiteral(writer,
                    string.IsNullOrEmpty(m.EntryPoint) ? m.Name : m.EntryPoint ?? m.Name);
                writer.Append(", ExactSpelling = true");
                if (m.StringMarshalling == "Utf16")
                {
                    writer.Append(", CharSet = CharSet.Unicode");
                }

                writer.AppendLine(")]");

                var unsafeMod = m.IsUnsafe ? "unsafe " : "";
                writer.Append($"public static {unsafeMod}extern {m.ReturnType} {m.Name}(");
                for (var i = 0; i < m.Parameters.Length; i++)
                {
                    var p = m.Parameters[i];
                    if (i > 0)
                    {
                        writer.Append(", ");
                    }

                    if (isUtf8 && p.Type is "string" or "string?")
                    {
                        writer.Append("[MarshalAs(UnmanagedType.LPUTF8Str)] ");
                    }

                    writer.Append($"{p.Type} {p.Name}");
                }

                writer.AppendLine(");");
                writer.AppendLine();
            }
        }

        return writer.ToString();
    }

    /// <summary>
    /// Emits GPU-only intrinsic stubs and collects their transpiler mapping entries.
    /// </summary>
    public static string EmitIntrinsics(NativeApiDefinition def,
        ImmutableArray<KeyValuePair<string, string>>.Builder mappingEntries)
    {
        using var writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line();
        writer.Line($"namespace {def.Namespace};");
        writer.Line();

        // Group by target class while preserving first-appearance order.
        var classNames = ImmutableArray.CreateBuilder<string>();
        foreach (var m in def.Methods)
        {
            var className = string.IsNullOrEmpty(m.ClassName) ? def.ClassName : m.ClassName ?? def.ClassName;
            if (!classNames.Contains(className))
            {
                classNames.Add(className);
            }
        }

        foreach (var className in classNames)
        {
            writer.Line("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
            writer.Line($"public static partial class {className}");
            using (writer.Scope())
            {
                writer.Line("#pragma warning disable IDE0051 // Remove unused private members");
                writer.Line("// ReSharper disable UnusedMember.Global");
                writer.Line();

                foreach (var m in def.Methods)
                {
                    var methodClass = string.IsNullOrEmpty(m.ClassName) ? def.ClassName : m.ClassName ?? def.ClassName;
                    if (methodClass != className)
                    {
                        continue;
                    }

                    EmitIntrinsicOverloads(writer, def, className, m, mappingEntries);
                }

                writer.Line("// ReSharper restore UnusedMember.Global");
                writer.Line("#pragma warning restore IDE0051");
            }

            writer.Line();
        }

        return writer.ToString();
    }

    /// <summary>
    /// Emits the compiler-side lookup table that maps intrinsic signatures to native names.
    /// </summary>
    public static string EmitMappingInfo(ImmutableArray<KeyValuePair<string, string>>.Builder mappingEntries)
    {
        using var writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line();
        writer.Line("namespace Kassyi.GSharp.Compiler.Transpiler;");
        writer.Line();
        writer.Line("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.Line("public static class NativeApiMapper");
        using (writer.Scope())
        {
            writer.Line("public static bool TryGetNativeName(string signature, out string nativeName)");
            using (writer.Scope())
            {
                writer.Line("switch (signature)");
                using (writer.Scope())
                {
                    foreach (var entry in mappingEntries)
                    {
                        writer.Line($"case \"{entry.Key}\": nativeName = \"{entry.Value}\"; return true;");
                    }
                }

                writer.Line("nativeName = string.Empty;");
                writer.Line("return false;");
            }
        }

        return writer.ToString();
    }

    /// <summary>
    /// Emits host launchers for kernels contained in a <see cref="NativeApiBindingKind.Module"/> definition.
    /// </summary>
    public static string EmitModuleBindings(NativeApiDefinition def)
    {
        var moduleName = def.ModuleName ?? string.Empty;

        using var writer = new SourceWriter();
        writer.AppendLine("// <auto-generated/>");
        writer.AppendLine("#nullable enable");
        writer.AppendLine("using System;");
        writer.AppendLine("using System.Runtime.InteropServices;");
        writer.AppendLine("using Kassyi.GSharp.Runtime;");
        writer.AppendLine("using Kassyi.GSharp.Runtime.Aot;");
        writer.AppendLine("using Kassyi.GSharp.Runtime.Interop;");
        writer.AppendLine();
        writer.AppendLine($"namespace {def.Namespace};");
        writer.AppendLine();
        writer.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.AppendLine($"public static partial class {def.ClassName}");
        using (writer.Scope())
        {
            ModuleKernelLaunchEmitter.EmitModuleCacheField(writer, moduleName);

            foreach (var m in def.Methods)
            {
                var parameters = CreateLaunchParameters(m);

                EmitDocumentation(writer, m);
                writer.Append($"public static void {m.Name}(");
                for (var i = 0; i < m.Parameters.Length; i++)
                {
                    var p = m.Parameters[i];
                    if (i > 0)
                    {
                        writer.Append(", ");
                    }

                    writer.Append($"{p.Type} {p.Name}");
                    if (!string.IsNullOrEmpty(p.DefaultValue))
                    {
                        writer.Append($" = {p.DefaultValue}");
                    }
                }

                writer.AppendLine(")");
                using (writer.Scope())
                {
                    var entryPoint = string.IsNullOrEmpty(m.EntryPoint) ? m.Name : m.EntryPoint ?? m.Name;
                    ModuleKernelLaunchEmitter.EmitLaunchBody(writer, moduleName, entryPoint, m.Name, parameters,
                        packContext: false);
                }

                writer.AppendLine();
            }
        }

        return writer.ToString();
    }

    /// <summary>
    /// Returns <see langword="true"/> when the library of <paramref name="def"/> cannot be found by the default
    /// probing logic: it declares platform candidates or is given as a relative or absolute path.
    /// </summary>
    public static bool RequiresResolver(NativeApiDefinition def)
    {
        if (def.BindingKind != NativeApiBindingKind.Library)
        {
            return false;
        }

        if (def.LibraryNames is { IsEmpty: false })
        {
            return true;
        }

        var libraryName = def.LibraryName ?? string.Empty;
        return libraryName.IndexOf('/') >= 0 || libraryName.IndexOf('\\') >= 0;
    }

    /// <summary>
    /// Emits a single per-assembly <c>DllImportResolver</c> that probes the candidates declared by every
    /// definition for which <see cref="RequiresResolver"/> is <see langword="true"/>.
    /// </summary>
    public static string EmitLibraryResolver(ImmutableArray<NativeApiDefinition> definitions)
    {
        using var writer = new SourceWriter();
        writer.AppendLine("// <auto-generated/>");
        writer.AppendLine("#nullable enable");
        writer.AppendLine("#pragma warning disable CA2255 // ModuleInitializer is required to register the resolver before first P/Invoke");
        writer.AppendLine("using System;");
        writer.AppendLine("using System.Reflection;");
        writer.AppendLine("using System.Runtime.CompilerServices;");
        writer.AppendLine("using System.Runtime.InteropServices;");
        writer.AppendLine();
        writer.AppendLine("namespace Kassyi.GSharp.Generated;");
        writer.AppendLine();
        writer.AppendLine("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.AppendLine($"internal static class {ResolverClassName}");
        using (writer.Scope())
        {
            var index = 0;
            foreach (var def in definitions)
            {
                EmitCandidateField(writer, index, "Windows", def.LibraryNames?.Windows, def.LibraryName);
                EmitCandidateField(writer, index, "Linux", def.LibraryNames?.Linux, def.LibraryName);
                EmitCandidateField(writer, index, "OSX", def.LibraryNames?.OSX, def.LibraryName);
                index++;
            }

            writer.AppendLine();
            writer.AppendLine("[ModuleInitializer]");
            writer.AppendLine("internal static void Register() =>");
            writer.AppendLine($"NativeLibrary.SetDllImportResolver(typeof({ResolverClassName}).Assembly, Resolve);");
            writer.AppendLine();
            writer.AppendLine("private static IntPtr Resolve(string libraryName, Assembly assembly, DllImportSearchPath? searchPath)");
            using (writer.Scope())
            {
                writer.AppendLine("switch (libraryName)");
                using (writer.Scope())
                {
                    index = 0;
                    foreach (var def in definitions)
                    {
                        writer.Append("case ");
                        ModuleKernelLaunchEmitter.AppendStringLiteral(writer, def.LibraryName ?? string.Empty);
                        writer.AppendLine(":");
                        writer.AppendLine("return global::Kassyi.GSharp.Runtime.Interop.NativeLibraryProbe.Load(assembly, searchPath,");
                        writer.AppendLine($"OperatingSystem.IsWindows() ? s_candidates{index}Windows : OperatingSystem.IsLinux() ? s_candidates{index}Linux : s_candidates{index}OSX);");
                        index++;
                    }
                }

                writer.AppendLine();
                writer.AppendLine("return IntPtr.Zero;");
            }
        }

        return writer.ToString();
    }

    private static void EmitCandidateField(SourceWriter writer, int index, string platform,
        ImmutableArray<string>? candidates, string? libraryName)
    {
        writer.Append($"private static readonly string[] s_candidates{index}{platform} = [");
        var first = true;
        if (candidates is { } list)
        {
            foreach (var candidate in list)
            {
                if (!first)
                {
                    writer.Append(", ");
                }

                ModuleKernelLaunchEmitter.AppendStringLiteral(writer, candidate);
                first = false;
            }
        }

        // The logical name is always the last resort so that a plain OS search still applies.
        if (!first)
        {
            writer.Append(", ");
        }

        ModuleKernelLaunchEmitter.AppendStringLiteral(writer, libraryName ?? string.Empty);
        writer.AppendLine("];");
    }

    private static ImmutableArray<ModuleKernelLaunchParameter> CreateLaunchParameters(ApiMethodDefinition method)
    {
        var builder = ImmutableArray.CreateBuilder<ModuleKernelLaunchParameter>(method.Parameters.Length);
        foreach (var p in method.Parameters)
        {
            var type = p.Type.AsSpan().Trim().ToString();
            string? elementType = null;
            if (type.EndsWith("[]", StringComparison.Ordinal))
            {
                elementType = type.AsSpan(0, type.Length - 2).TrimEnd().ToString();
            }

            builder.Add(new ModuleKernelLaunchParameter(p.Name, type, elementType, CopyIn: true, CopyOut: true));
        }

        return builder.MoveToImmutable();
    }

    private static void EmitIntrinsicOverloads(SourceWriter writer, NativeApiDefinition def, string className,
        ApiMethodDefinition m, ImmutableArray<KeyValuePair<string, string>>.Builder mappingEntries)
    {
        var types = m.TypeTemplate?.Types ?? ImmutableArray<string>.Empty;
        if (types.IsEmpty)
        {
            types = ImmutableArray.Create(string.Empty);
        }

        var placeholder = m.TypeTemplate?.Placeholder ?? "T";

        foreach (var t in types)
        {
            var returnType = ReplacePlaceholder(m.ReturnType, placeholder, t);

            EmitDocumentation(writer, m);

            var nativeName = m.NativeName ?? m.Name;
            writer.Line($"[Kassyi.GSharp.Core.CudaIntrinsic(\"{nativeName}\")]");

            writer.Append($"public static {returnType} {m.Name}");
            using (writer.Parentheses())
            {
                for (var i = 0; i < m.Parameters.Length; i++)
                {
                    var p = m.Parameters[i];
                    if (i > 0)
                    {
                        writer.Append(", ");
                    }

                    var pType = ReplacePlaceholder(p.Type, placeholder, t);
                    writer.Append($"{pType} {p.Name}");
                    if (!string.IsNullOrEmpty(p.DefaultValue))
                    {
                        writer.Append($" = {p.DefaultValue}");
                    }
                }
            }

            writer.AppendLine(returnType == "void"
                ? " => Kassyi.GSharp.Core.GpuOnlyException.Throw();"
                : $" => Kassyi.GSharp.Core.GpuOnlyException.Throw<{returnType}>();");
            writer.Line();

            var signature = new StringBuilder();
            signature.Append($"{def.Namespace}.{className}.{m.Name}(");
            for (var i = 0; i < m.Parameters.Length; i++)
            {
                if (i > 0)
                {
                    signature.Append(", ");
                }

                signature.Append(ReplacePlaceholder(m.Parameters[i].Type, placeholder, t));
            }

            signature.Append(')');
            mappingEntries.Add(new KeyValuePair<string, string>(signature.ToString(), nativeName));
        }
    }

    private static void EmitDocumentation(SourceWriter writer, ApiMethodDefinition m)
    {
        if (!string.IsNullOrEmpty(m.Summary))
        {
            writer.Line($"/// <summary>{EscapeXml(m.Summary ?? string.Empty)}</summary>");
        }

        foreach (var p in m.Parameters)
        {
            if (!string.IsNullOrEmpty(p.Description))
            {
                writer.Line($"/// <param name=\"{p.Name}\">{EscapeXml(p.Description ?? string.Empty)}</param>");
            }
        }

        if (!string.IsNullOrEmpty(m.ReturnDescription))
        {
            writer.Line($"/// <returns>{EscapeXml(m.ReturnDescription ?? string.Empty)}</returns>");
        }
    }

    private static string ReplacePlaceholder(string template, string placeholder, string replacement)
    {
        if (string.IsNullOrEmpty(placeholder) || template.IndexOf(placeholder, StringComparison.Ordinal) < 0)
        {
            return template;
        }

        var sb = new StringBuilder(template);
        sb.Replace(placeholder, replacement);
        return sb.ToString();
    }

    /// <summary>
    /// Escapes XML special characters and keeps multi-line text inside the <c>///</c> comment.
    /// </summary>
    private static string EscapeXml(string text)
    {
        if (text.IndexOf('&') < 0 && text.IndexOf('<') < 0 && text.IndexOf('>') < 0 && text.IndexOf('\n') < 0)
        {
            return text;
        }

        var sb = new StringBuilder(text.Length + 16);
        foreach (var c in text)
        {
            switch (c)
            {
                case '&':
                    sb.Append("&amp;");
                    break;
                case '<':
                    sb.Append("&lt;");
                    break;
                case '>':
                    sb.Append("&gt;");
                    break;
                case '\n':
                    sb.Append("\n/// ");
                    break;
                case '\r':
                    break;
                default:
                    sb.Append(c);
                    break;
            }
        }

        return sb.ToString();
    }
}
