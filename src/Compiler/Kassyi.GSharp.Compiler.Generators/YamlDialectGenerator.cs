using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using YamlDotNet.Serialization;
using YamlDotNet.Serialization.NamingConventions;

namespace Kassyi.GSharp.Compiler.Generators;

[Generator]
public class YamlDialectGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var yamlFiles = context.AdditionalTextsProvider
            .Where(text => text.Path.EndsWith(".yml", StringComparison.OrdinalIgnoreCase) || text.Path.EndsWith(".yaml", StringComparison.OrdinalIgnoreCase))
            .Select((text, cancellationToken) => text.GetText(cancellationToken)?.ToString())
            .Where(text => text != null);

        var dialectDefinitions = yamlFiles.Select((text, _) =>
        {
            var deserializer = new DeserializerBuilder()
                .WithNamingConvention(PascalCaseNamingConvention.Instance)
                .IgnoreUnmatchedProperties()
                .Build();

            try
            {
                return deserializer.Deserialize<DialectDefinition>(text!);
            }
            catch
            {
                return null;
            }
        }).Where(def => def != null && !string.IsNullOrEmpty(def.Name));

        var allDefinitions = dialectDefinitions.Collect();

        context.RegisterSourceOutput(allDefinitions, (spc, definitions) =>
        {
            var defMap = definitions.ToDictionary(d => d!.Name, d => d!);
            
            // Add a base class
            spc.AddSource("YamlDialectBase.g.cs", SourceText.From(GenerateBaseClass(), Encoding.UTF8));

            foreach (var def in definitions)
            {
                string source = GenerateDialectClass(def!, defMap);
                spc.AddSource($"{def!.Name}Dialect.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    private string GenerateBaseClass()
    {
        return @"// <auto-generated/>
#nullable enable
using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Kassyi.GSharp.Compiler.Transpiler;
using Kassyi.GSharp.Compiler.Transpiler.Dialects;

namespace Kassyi.GSharp.Compiler.Dialects;

public abstract class YamlDialectBase : ITranspilerDialect
{
    public virtual IEnumerable<string> RequiredHeaders => Enumerable.Empty<string>();
    public virtual string StructPrefix => string.Empty;
    public virtual string MethodPrefix => string.Empty;

    public virtual void AppendType(ref TranspileContext context, ITypeSymbol? typeSymbol)
    {
        if (typeSymbol == null)
        {
            context.Writer.Append(""void"");
            return;
        }

        if (typeSymbol is IArrayTypeSymbol array)
        {
            AppendType(ref context, array.ElementType);
            context.Writer.Append(""*"");
            return;
        }

        if (typeSymbol is IPointerTypeSymbol pointer)
        {
            AppendType(ref context, pointer.PointedAtType);
            context.Writer.Append(""*"");
            return;
        }

        var format = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
            SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions & ~SymbolDisplayMiscellaneousOptions.UseSpecialTypes);
        var name = typeSymbol.ToDisplayString(format).Replace(""global::"", """");
        
        if (TryMapType(name, out var mappedType))
        {
            context.Writer.Append(mappedType);
            return;
        }

        context.Writer.AppendFullyQualifiedCppName(typeSymbol);
        
        if (typeSymbol is INamedTypeSymbol { IsGenericType: true } namedType)
        {
            context.Writer.Append(""<"");
            for (int i = 0; i < namedType.TypeArguments.Length; i++)
            {
                AppendType(ref context, namedType.TypeArguments[i]);
                if (i < namedType.TypeArguments.Length - 1)
                {
                    context.Writer.Append("", "");
                }
            }
            context.Writer.Append("">"");
        }
    }

    protected virtual bool TryMapType(string fullyQualifiedName, out string mappedType)
    {
        mappedType = string.Empty;
        return false;
    }

    public virtual bool TryMapIntrinsic(ISymbol symbol, out string mappedExpression)
    {
        var intrinsicAttr = symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == ""CudaIntrinsicAttribute"");
        if (intrinsicAttr is { ConstructorArguments.Length: > 0 })
        {
            mappedExpression = intrinsicAttr.ConstructorArguments[0].Value?.ToString() ?? symbol.Name;
            return true;
        }

        if (symbol.ContainingType != null)
        {
            var patternAttr = symbol.ContainingType.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == ""CudaIntrinsicPatternAttribute"");
            if (patternAttr is { ConstructorArguments.Length: > 0 })
            {
                var pattern = patternAttr.ConstructorArguments[0].Value?.ToString() ?? ""{0}"";
                mappedExpression = string.Format(pattern, symbol.Name.ToLowerInvariant());
                return true;
            }
        }

        var name = symbol.ToDisplayString(new SymbolDisplayFormat(
            memberOptions: SymbolDisplayMemberOptions.IncludeParameters | SymbolDisplayMemberOptions.IncludeContainingType,
            parameterOptions: SymbolDisplayParameterOptions.IncludeType | SymbolDisplayParameterOptions.IncludeParamsRefOut,
            typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
            miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes
        )).Replace(""global::"", """");

        return TryMapIntrinsicCore(name, out mappedExpression);
    }

    protected virtual bool TryMapIntrinsicCore(string signature, out string mappedExpression)
    {
        mappedExpression = string.Empty;
        return false;
    }

    public virtual (bool IsRefPointer, bool IsPointerType, bool HasRestrict) AppendParameter(ref TranspileContext context, ParameterSyntax p, ITypeSymbol? typeSymbol)
    {
        bool isRefPointer = p.Modifiers.Any(SyntaxKind.RefKeyword) || p.Modifiers.Any(SyntaxKind.OutKeyword);
        bool isPointerType = typeSymbol is IPointerTypeSymbol || typeSymbol is IArrayTypeSymbol;
        
        AppendType(ref context, typeSymbol);
        if (isRefPointer)
        {
            context.Writer.Append(""* __restrict__ "");
        }
        
        return (isRefPointer, isPointerType, isRefPointer);
    }

    public virtual int GetApproximateSize(ITypeSymbol typeSymbol) => 4;

    public virtual CSharpSyntaxRewriter? GetAstPreProcessor(SemanticModel semanticModel) => null;

    public virtual CSharpSyntaxVisitor<bool> GetInterceptorVisitor(ref TranspileContext context)
    {
        return new DefaultInterceptorVisitor();
    }

    private class DefaultInterceptorVisitor : CSharpSyntaxVisitor<bool>
    {
        public override bool DefaultVisit(SyntaxNode node) => false;
    }
}
";
    }

    private string GenerateDialectClass(DialectDefinition def, Dictionary<string, DialectDefinition> definitions)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Kassyi.GSharp.Compiler.Transpiler;");
        sb.AppendLine("using Kassyi.GSharp.Compiler.Transpiler.Dialects;");
        sb.AppendLine();
        sb.AppendLine("namespace Kassyi.GSharp.Compiler.Dialects;");
        sb.AppendLine();
        
        string baseClass = "YamlDialectBase";
        if (!string.IsNullOrEmpty(def.Inherits))
        {
            baseClass = $"{def.Inherits}Dialect";
        }

        sb.AppendLine($"public class {def.Name}Dialect : {baseClass}");
        sb.AppendLine("{");

        // Headers
        var headers = new HashSet<string>();
        CollectHeaders(def, definitions, headers);
        if (headers.Count > 0)
        {
            sb.AppendLine("    public override IEnumerable<string> RequiredHeaders => new string[] {");
            foreach (var h in headers) sb.AppendLine($"        \"{h}\",");
            sb.AppendLine("    };");
        }

        // StructPrefix
        string structPrefix = GetInheritedValue(def, definitions, d => d.StructPrefix);
        if (structPrefix != null)
        {
            sb.AppendLine($"    public override string StructPrefix => \"{structPrefix}\";");
        }

        // MethodPrefix
        string methodPrefix = GetInheritedValue(def, definitions, d => d.MethodPrefix);
        if (methodPrefix != null)
        {
            sb.AppendLine($"    public override string MethodPrefix => \"{methodPrefix}\";");
        }

        // Types
        if (def.Types != null && def.Types.Count > 0)
        {
            sb.AppendLine("    protected override bool TryMapType(string fullyQualifiedName, out string mappedType)");
            sb.AppendLine("    {");
            sb.AppendLine("        switch (fullyQualifiedName)");
            sb.AppendLine("        {");
            foreach (var kvp in def.Types)
            {
                sb.AppendLine($"            case \"{kvp.Key}\": mappedType = \"{kvp.Value}\"; return true;");
            }
            sb.AppendLine("        }");
            sb.AppendLine("        return base.TryMapType(fullyQualifiedName, out mappedType);");
            sb.AppendLine("    }");
        }

        // Intrinsics
        if (def.Intrinsics != null && def.Intrinsics.Count > 0)
        {
            sb.AppendLine("    protected override bool TryMapIntrinsicCore(string signature, out string mappedExpression)");
            sb.AppendLine("    {");
            sb.AppendLine("        switch (signature)");
            sb.AppendLine("        {");
            foreach (var kvp in def.Intrinsics)
            {
                sb.AppendLine($"            case \"{kvp.Key}\": mappedExpression = \"{kvp.Value}\"; return true;");
            }
            sb.AppendLine("        }");
            sb.AppendLine("        return base.TryMapIntrinsicCore(signature, out mappedExpression);");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private void CollectHeaders(DialectDefinition def, Dictionary<string, DialectDefinition> definitions, HashSet<string> headers)
    {
        if (!string.IsNullOrEmpty(def.Inherits) && definitions.TryGetValue(def.Inherits, out var parent))
        {
            CollectHeaders(parent, definitions, headers);
        }
        if (def.RequiredHeaders != null)
        {
            foreach (var h in def.RequiredHeaders) headers.Add(h);
        }
    }

    private string GetInheritedValue(DialectDefinition def, Dictionary<string, DialectDefinition> definitions, Func<DialectDefinition, string> selector)
    {
        var val = selector(def);
        if (!string.IsNullOrEmpty(val)) return val;
        
        if (!string.IsNullOrEmpty(def.Inherits) && definitions.TryGetValue(def.Inherits, out var parent))
        {
            return GetInheritedValue(parent, definitions, selector);
        }
        return null;
    }
}
