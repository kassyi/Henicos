using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis.CSharp;

namespace Kassyi.GSharp.Compiler.Generators;

public sealed class DiagnosticDefinition
{
    public string Name { get; set; } = "";
    public string Id { get; set; } = "";
    public string Title { get; set; } = "";
    public string MessageFormat { get; set; } = "";
    public string Category { get; set; } = "";
    public string DefaultSeverity { get; set; } = "";
    public bool IsEnabledByDefault { get; set; }
    public bool IsObsolete { get; set; }
}

public static partial class DiagnosticGenerator
{
    private static readonly JsonSerializerOptions s_jsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
    };

    public static void Run(string inputFile, string outputDir)
    {
        Directory.CreateDirectory(outputDir);

        var json = File.ReadAllText(inputFile);
        var diagnostics = JsonSerializer.Deserialize<List<DiagnosticDefinition>>(json, s_jsonOptions);
        if (diagnostics == null)
        {
            return;
        }

        var source = GenerateSource(diagnostics);
        File.WriteAllText(Path.Combine(outputDir, "GSharpDiagnostics.g.cs"), source, Encoding.UTF8);
    }

    public static string GenerateSource(IReadOnlyList<DiagnosticDefinition> diagnostics)
    {
        using var writer = new SourceWriter();
        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line("using Microsoft.CodeAnalysis;");
        writer.Line();
        writer.Line("namespace Kassyi.GSharp.Compiler.Diagnostics;");
        writer.Line();
        writer.Line("public static partial class GSharpDiagnostics");

        using (writer.Scope())
        {
            var seenIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var seenNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (var diag in diagnostics)
            {
                EmitDiagnosticDescriptor(writer, diag, seenIds, seenNames);
            }
        }

        return writer.ToString();
    }

    private static void EmitDiagnosticDescriptor(
        SourceWriter writer,
        DiagnosticDefinition diag,
        ISet<string> seenIds,
        ISet<string> seenNames)
    {
        ValidateDiagnostic(writer, diag, seenIds, seenNames);

        if (diag.IsObsolete)
        {
            writer.Line("[Obsolete(\"This diagnostic is obsolete and no longer emitted by the compiler.\")]");
        }

        var fieldName = SyntaxFacts.IsValidIdentifier(diag.Name)
            ? diag.Name
            : $"_InvalidIdentifier_{seenNames.Count}";

        writer.Line($"public static readonly DiagnosticDescriptor {fieldName} = new(");
        using (writer.Scope("", ");"))
        {
            writer.Line($"id: \"{diag.Id}\",");
            writer.Line($"title: \"{Escape(diag.Title)}\",");
            writer.Line($"messageFormat: \"{Escape(diag.MessageFormat)}\",");
            writer.Line($"category: \"{Escape(diag.Category)}\",");
            writer.Line($"defaultSeverity: DiagnosticSeverity.{diag.DefaultSeverity},");
            writer.Line($"isEnabledByDefault: {(diag.IsEnabledByDefault ? "true" : "false")}");
        }

        writer.Line();
    }

    private static void ValidateDiagnostic(
        SourceWriter writer,
        DiagnosticDefinition diag,
        ISet<string> seenIds,
        ISet<string> seenNames)
    {
        // 1. Schema Warning
        if (string.IsNullOrWhiteSpace(diag.Title))
        {
            writer.Line("#warning Diagnostic schema warning: Title is missing for a diagnostic entry.");
        }

        // 2. ID Validation & Duplication (Error)
        if (string.IsNullOrWhiteSpace(diag.Id))
        {
            writer.Line("#error Diagnostic ID is missing in diagnostics.json.");
        }
        else if (!IdFormatRegex().IsMatch(diag.Id))
        {
            writer.Line($"#error Invalid diagnostic ID format '{diag.Id}' in diagnostics.json. Expected 3 alphanumeric characters followed by 4 digits (e.g. GSH0001).");
        }
        else if (!seenIds.Add(diag.Id))
        {
            writer.Line($"#error Duplicate diagnostic ID found in diagnostics.json: {diag.Id}");
        }

        // 3. Name Validation & Duplication (Error)
        if (string.IsNullOrWhiteSpace(diag.Name))
        {
            writer.Line($"#error Diagnostic Name is missing in diagnostics.json (ID: {diag.Id}).");
        }
        else if (!SyntaxFacts.IsValidIdentifier(diag.Name))
        {
            writer.Line($"#error Invalid diagnostic Name '{diag.Name}' in diagnostics.json. It must be a valid C# identifier.");
        }
        else if (!seenNames.Add(diag.Name))
        {
            writer.Line($"#error Duplicate diagnostic Name found in diagnostics.json: {diag.Name}");
        }
    }

    private static string Escape(string? s) => s?.Replace("\"", "\\\"") ?? "";

    [GeneratedRegex(@"^[A-Za-z0-9]{3}\d{4}$")]
    private static partial Regex IdFormatRegex();
}
