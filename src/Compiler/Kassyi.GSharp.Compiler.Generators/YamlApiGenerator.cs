using YamlDotNet.Serialization;
using YamlDotNet.Serialization.NamingConventions;

namespace Kassyi.GSharp.Compiler.Generators;

public static class YamlApiGenerator
{
    private static readonly IDeserializer s_deserializer = new DeserializerBuilder()
        .WithNamingConvention(CamelCaseNamingConvention.Instance)
        .IgnoreUnmatchedProperties()
        .Build();

    public static void Run(string inputDir, string outputDir)
    {
        Directory.CreateDirectory(outputDir);

        var definitions = new List<NativeApiDefinition>();

        foreach (var path in Directory.GetFiles(inputDir, "*.*", SearchOption.AllDirectories))
        {
            if (!path.EndsWith(".yml", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".yaml", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var text = File.ReadAllText(path);
            try
            {
                var def = s_deserializer.Deserialize<NativeApiDefinition>(text);
                if (!string.IsNullOrEmpty(def.Namespace))
                {
                    definitions.Add(def);
                }
            }
            catch
            {
                // Ignore deserialization failures
            }
        }

        var mappingEntries = new List<(string Signature, string NativeName)>();

        foreach (var def in definitions)
        {
            var isDriverApi = !string.IsNullOrEmpty(def.LibraryName);
            var source = isDriverApi ? GenerateDriverApi(def) : GenerateIntrinsics(def, mappingEntries);
            var fileName = isDriverApi ? $"{def.ClassName}.g.cs" : $"{def.ClassName}Intrinsics.g.cs";
            
            File.WriteAllText(Path.Combine(outputDir, fileName), source, Encoding.UTF8);
        }

        // Generate mapping info for compiler
        var mappingSource = GenerateMappingInfo(mappingEntries);
        File.WriteAllText(Path.Combine(outputDir, "NativeApiMapper.g.cs"), mappingSource, Encoding.UTF8);
    }

    private static string GenerateDriverApi(NativeApiDefinition def)
    {
        using var writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line("using System.Runtime.CompilerServices;");
        writer.Line("using System.Runtime.InteropServices;");
        writer.Line();
        writer.Line($"namespace {def.Namespace};");
        writer.Line();
        
        writer.Line("// ReSharper disable InconsistentNaming");
        writer.Line($"public static partial class {def.ClassName}");
        using (writer.Scope())
        {
            foreach (var m in def.Methods)
            {
                var importArgs = new List<string> { $"\"{def.LibraryName}\"" };
                if (!string.IsNullOrEmpty(m.EntryPoint))
                {
                    importArgs.Add($"EntryPoint = \"{m.EntryPoint}\"");
                }
                if (!string.IsNullOrEmpty(m.StringMarshalling))
                {
                    importArgs.Add($"StringMarshalling = StringMarshalling.{m.StringMarshalling}");
                }
                
                if (!string.IsNullOrEmpty(m.Summary))
                {
                    writer.Line($"/// <summary>{EscapeXml(m.Summary)}</summary>");
                }
                foreach (var p in m.Parameters)
                {
                    if (!string.IsNullOrEmpty(p.Description))
                    {
                        writer.Line($"/// <param name=\"{p.Name}\">{EscapeXml(p.Description)}</param>");
                    }
                }
                if (!string.IsNullOrEmpty(m.ReturnDescription))
                {
                    writer.Line($"/// <returns>{EscapeXml(m.ReturnDescription)}</returns>");
                }

                writer.Line($"[LibraryImport({string.Join(", ", importArgs)})]");
                writer.Line("[UnmanagedCallConv(CallConvs = [typeof(CallConvStdcall)])]");
                
                var unsafeMod = m.IsUnsafe ? "unsafe " : "";
                
                writer.Append($"public static {unsafeMod}partial {m.ReturnType} {m.Name}");
                using (writer.Parentheses())
                {
                    for (int i = 0; i < m.Parameters.Count; i++)
                    {
                        var p = m.Parameters[i];
                        if (i > 0)
                        {
                            writer.Append(", ");
                        }

                        writer.Append($"{p.Type} {p.Name}");
                    }
                }
                writer.AppendLine(";");
                writer.Line();
            }
        }
        
        return writer.ToString();
    }

    private static string GenerateIntrinsics(NativeApiDefinition def, List<(string Signature, string NativeName)> mappingEntries)
    {
        using var writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line();
        writer.Line($"namespace {def.Namespace};");
        writer.Line();
        
        var classGroups = new Dictionary<string, List<ApiMethodDefinition>>();
        foreach (var m in def.Methods)
        {
            var className = string.IsNullOrEmpty(m.ClassName) ? def.ClassName : m.ClassName;
            if (!classGroups.TryGetValue(className, out var list))
            {
                list = [];
                classGroups[className] = list;
            }

            list.Add(m);
        }
        
        foreach (var group in classGroups)
        {
            writer.Line($"public static partial class {group.Key}");
            using (writer.Scope())
            {
                writer.Line("#pragma warning disable IDE0051 // Remove unused private members");
                writer.Line("// ReSharper disable UnusedMember.Global");
                writer.Line();
                
                foreach (var m in group.Value)
                {
                    var types = m.TypeTemplate?.Types ?? [""];
                    var placeholder = m.TypeTemplate?.Placeholder ?? "T";
                    
                    foreach (var t in types)
                    {
                        var returnType = m.ReturnType.Replace(placeholder, t);
                        
                        if (!string.IsNullOrEmpty(m.Summary))
                        {
                            writer.Line($"/// <summary>{EscapeXml(m.Summary)}</summary>");
                        }
                        
                        foreach (var p in m.Parameters)
                        {
                            if (!string.IsNullOrEmpty(p.Description))
                            {
                                writer.Line($"/// <param name=\"{p.Name}\">{EscapeXml(p.Description)}</param>");
                            }
                        }
                        
                        if (!string.IsNullOrEmpty(m.ReturnDescription))
                        {
                            writer.Line($"/// <returns>{EscapeXml(m.ReturnDescription)}</returns>");
                        }
                        
                        var nativeName = m.NativeName ?? m.Name;
                        writer.Line($"[Kassyi.GSharp.Core.CudaIntrinsic(\"{nativeName}\")]");
                        
                        writer.Append($"public static {returnType} {m.Name}");
                        using (writer.Parentheses())
                        {
                            for (int i = 0; i < m.Parameters.Count; i++)
                            {
                                var p = m.Parameters[i];
                                if (i > 0)
                                {
                                    writer.Append(", ");
                                }

                                var pType = p.Type.Replace(placeholder, t);
                                writer.Append($"{pType} {p.Name}");
                                if (!string.IsNullOrEmpty(p.DefaultValue))
                                {
                                    writer.Append($" = {p.DefaultValue}");
                                }
                            }
                        }
                        
                        if (returnType == "void")
                        {
                            writer.AppendLine(" => Kassyi.GSharp.Core.GpuOnlyException.Throw();");
                        }
                        else
                        {
                            writer.AppendLine($" => Kassyi.GSharp.Core.GpuOnlyException.Throw<{returnType}>();");
                        }
                        writer.Line();
                        
                        // Mapping entry
                        var sigBuilder = new StringBuilder();
                        sigBuilder.Append($"{def.Namespace}.{group.Key}.{m.Name}(");
                        for (int i = 0; i < m.Parameters.Count; i++)
                        {
                            var p = m.Parameters[i];
                            if (i > 0)
                            {
                                sigBuilder.Append(", ");
                            }

                            var pType = p.Type.Replace(placeholder, t);
                            sigBuilder.Append(pType);
                        }
                        sigBuilder.Append(")");
                        
                        mappingEntries.Add((sigBuilder.ToString(), nativeName));
                    }
                }
                
                writer.Line("// ReSharper restore UnusedMember.Global");
                writer.Line("#pragma warning restore IDE0051");
            }
            writer.Line();
        }
        
        return writer.ToString();
    }

    private static string GenerateMappingInfo(List<(string Signature, string NativeName)> mappingEntries)
    {
        using var writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line();
        writer.Line("namespace Kassyi.GSharp.Compiler.Transpiler;");
        writer.Line();
        writer.Line("public static class NativeApiMapper");
        using (writer.Scope())
        {
            writer.Line("public static bool TryGetNativeName(string signature, out string nativeName)");
            using (writer.Scope())
            {
                writer.Line("switch (signature)");
                using (writer.Scope())
                {
                    foreach (var entry in mappingEntries)
                    {
                        writer.Line($"case \"{entry.Signature}\": nativeName = \"{entry.NativeName}\"; return true;");
                    }
                }
                
                writer.Line("nativeName = string.Empty;");
                writer.Line("return false;");
            }
        }
        
        return writer.ToString();
    }

    private static string EscapeXml(string text)
    {
        if (string.IsNullOrEmpty(text))
        {
            return text;
        }

        return text
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }
}
