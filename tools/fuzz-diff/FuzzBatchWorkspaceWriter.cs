using System.Text;

namespace Kassyi.GSharp.Tools.FuzzDiff;

/// <summary>
/// Writes the generated batch source files and standalone temporary project scaffolds (<c>FuzzBatch.Cpu.csproj</c> and <c>FuzzBatch.Cuda.csproj</c>).
/// </summary>
public static class FuzzBatchWorkspaceWriter
{
    private static readonly UTF8Encoding s_utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

    /// <summary>
    /// Writes <c>FuzzBatchKernels.cu.cs</c>, <c>FuzzBatchCases.cs</c>, and (when <paramref name="repoRoot"/> is supplied)
    /// the standalone temporary project files in the parent workspace directory.
    /// </summary>
    public static void WriteBatch(GeneratedBatch batch, string outDir, string? repoRoot = null, string? cudaArch = null)
    {
        ArgumentNullException.ThrowIfNull(batch);
        ArgumentException.ThrowIfNullOrWhiteSpace(outDir);

        string fullOutDir = Path.GetFullPath(outDir);
        Directory.CreateDirectory(fullOutDir);

        string kernelsPath = Path.Combine(fullOutDir, "FuzzBatchKernels.cu.cs");
        string casesPath = Path.Combine(fullOutDir, "FuzzBatchCases.cs");

        File.WriteAllText(kernelsPath, batch.KernelsSource, s_utf8NoBom);
        File.WriteAllText(casesPath, batch.CasesSource, s_utf8NoBom);

        if (!string.IsNullOrWhiteSpace(repoRoot))
        {
            string workDir = Path.GetFileName(fullOutDir).Equals("Generated", StringComparison.OrdinalIgnoreCase)
                ? (Path.GetDirectoryName(fullOutDir) ?? fullOutDir)
                : fullOutDir;
            WriteProjectScaffolds(workDir, fullOutDir, Path.GetFullPath(repoRoot), cudaArch);
        }
    }

    /// <summary>
    /// Writes <c>Directory.Build.props</c>, <c>FuzzBatchHarnessStubs.cs</c>, <c>FuzzBatch.Cpu.csproj</c>, and <c>FuzzBatch.Cuda.csproj</c>
    /// into <paramref name="workDir"/> if they do not exist or if their contents changed.
    /// </summary>
    public static void WriteProjectScaffolds(string workDir, string generatedDir, string repoRoot, string? cudaArch = null)
    {
        Directory.CreateDirectory(workDir);

        string propsPath = Path.Combine(workDir, "Directory.Build.props");
        WriteIfChanged(propsPath, BuildDirectoryBuildProps());

        string stubsPath = Path.Combine(generatedDir, "FuzzBatchHarnessStubs.cs");
        WriteIfChanged(stubsPath, BuildHarnessStubs());

        string relGen = NormalizeSlashes(Path.GetRelativePath(workDir, generatedDir));
        string relRepo = NormalizeSlashes(Path.GetRelativePath(workDir, repoRoot));

        string cpuProjPath = Path.Combine(workDir, "FuzzBatch.Cpu.csproj");
        WriteIfChanged(cpuProjPath, BuildProjectXml(dialect: "Cpu", relGen, relRepo, cudaArch: null));

        string cudaProjPath = Path.Combine(workDir, "FuzzBatch.Cuda.csproj");
        WriteIfChanged(cudaProjPath, BuildProjectXml(dialect: "Cuda", relGen, relRepo, cudaArch));
    }

    private static string BuildDirectoryBuildProps() =>
        """
        <Project>
          <!-- Isolated temporary fuzz batch build configuration: stops root analyzer/StyleCop inheritance. -->
          <PropertyGroup>
            <GSharpHostOs Condition="$([MSBuild]::IsOSPlatform('Windows'))">win</GSharpHostOs>
            <GSharpHostOs Condition="'$(GSharpHostOs)' == '' and $([MSBuild]::IsOSPlatform('Linux'))">linux</GSharpHostOs>
            <GSharpHostOs Condition="'$(GSharpHostOs)' == '' and $([MSBuild]::IsOSPlatform('OSX'))">osx</GSharpHostOs>
            <GSharpHostOs Condition="'$(GSharpHostOs)' == ''">unix</GSharpHostOs>

            <BaseOutputPath>bin\$(GSharpHostOs)\$(MSBuildProjectName)\</BaseOutputPath>
            <BaseIntermediateOutputPath>obj\$(GSharpHostOs)\$(MSBuildProjectName)\</BaseIntermediateOutputPath>
            <DefaultItemExcludes>$(DefaultItemExcludes);bin\**;obj\**;findings\**</DefaultItemExcludes>

            <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
            <GenerateDocumentationFile>false</GenerateDocumentationFile>
            <GSharpExportDeviceCode>false</GSharpExportDeviceCode>
            <GSharpGenerateSnapshotTestCases>false</GSharpGenerateSnapshotTestCases>
            <NoWarn>$(NoWarn);GS0001;GS0002;CS0162;CS0169;CS0219;CS1591;CS1717;CS1718;CS8019;CS8321;SA1600</NoWarn>
          </PropertyGroup>
        </Project>
        """;

    private static string BuildHarnessStubs()
    {
        using var writer = new SourceWriter();
        writer.AppendLine("// <auto-generated />");
        writer.AppendLine("#nullable enable");
        writer.AppendLine("global using System.Linq;");
        writer.AppendLine("global using Kassyi.GSharp.Runtime.Aot;");
        writer.AppendLine("global using Xunit;");
        writer.AppendLine("using System;");
        writer.AppendLine();

        using (writer.Scope("namespace Xunit"))
        {
            writer.AppendLine("[AttributeUsage(AttributeTargets.Method, AllowMultiple = false)]");
            using (writer.Scope("internal sealed class FactAttribute : Attribute"))
            {
            }

            writer.AppendLine("[AttributeUsage(AttributeTargets.Method, AllowMultiple = false)]");
            using (writer.Scope("internal sealed class TheoryAttribute : Attribute"))
            {
            }
        }

        writer.AppendLine();
        using (writer.Scope("namespace Kassyi.GSharp.Compiler.Marshaling"))
        {
            using (writer.Scope("internal static class AotHostNames"))
            {
                writer.AppendLine("public static string ToSafeIdentifier(string name) => name.Replace('.', '_');");
            }
        }

        writer.AppendLine();
        using (writer.Scope("namespace Kassyi.GSharp.Tests.Shared.Differential"))
        {
            using (writer.Scope("public sealed record KnownDivergence(string Case, string Column, DiffPath Paths, int Issue, DiffHost Hosts = DiffHost.Any, Predicate<LaunchShape>? ShapePredicate = null)"))
            {
                writer.AppendLine("public const string ExceptionColumn = \"$exception\";");
                writer.AppendLine("public bool AppliesToThisHost => (Hosts & (OperatingSystem.IsWindows() ? DiffHost.Windows : DiffHost.Unix)) != 0;");
                writer.AppendLine("public bool Covers(string caseName, string column, DiffPath path) => Case == caseName && Column == column && (Paths & path) != 0 && ShapePredicate is null;");
                writer.AppendLine("public bool Covers(string caseName, string column, DiffPath path, LaunchShape shape) => Case == caseName && Column == column && (Paths & path) != 0 && (ShapePredicate is null || ShapePredicate(shape));");
                writer.AppendLine("public override string ToString() => $\"\\\"{Column}\\\" on {DiffPaths.Format(Paths)} (#{Issue})\";");
            }

            using (writer.Scope("public static class KnownDivergences"))
            {
                writer.AppendLine("public static System.Collections.Generic.IReadOnlyList<KnownDivergence> All { get; } = [];");
            }

            using (writer.Scope("internal static class CudaCapability"))
            {
                using (writer.Scope("public static void EnsureGpuAvailable()"))
                {
                    using (writer.Scope("if (!GpuKernelLoader.IsDriverAvailable)"))
                    {
                        writer.AppendLine("throw new System.InvalidOperationException(\"NVIDIA GPU and CUDA Driver are required to run CUDA differential fuzz batches.\");");
                    }
                }
            }
        }

        return writer.ToString();
    }

    private static string BuildProjectXml(string dialect, string relGen, string relRepo, string? cudaArch)
    {
        bool isCuda = string.Equals(dialect, "Cuda", StringComparison.OrdinalIgnoreCase);
        string defineConstant = isCuda ? "GSHARP_CUDA" : "GSHARP_CPU";
        var sb = new StringBuilder();
        sb.AppendLine("<Project Sdk=\"Microsoft.NET.Sdk\">");
        sb.AppendLine("  <PropertyGroup>");
        sb.AppendLine("    <OutputType>Exe</OutputType>");
        sb.AppendLine("    <TargetFramework>net10.0</TargetFramework>");
        sb.AppendLine("    <ImplicitUsings>enable</ImplicitUsings>");
        sb.AppendLine("    <Nullable>enable</Nullable>");
        sb.AppendLine("    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>");
        sb.AppendLine($"    <GSharpTargetDialect>{dialect}</GSharpTargetDialect>");
        sb.AppendLine("    <GSharpExportDeviceCode>false</GSharpExportDeviceCode>");
        sb.AppendLine("    <GSharpGenerateSnapshotTestCases>false</GSharpGenerateSnapshotTestCases>");
        sb.AppendLine($"    <GSharpCompilerTaskAssembly>$(MSBuildThisFileDirectory){relRepo}/src/Compiler/Kassyi.GSharp.Compiler.Tasks/bin/$(GSharpHostOs)/$(Configuration)/netstandard2.0/Kassyi.GSharp.Compiler.Tasks.dll</GSharpCompilerTaskAssembly>");
        sb.AppendLine($"    <DefineConstants>$(DefineConstants);{defineConstant}</DefineConstants>");
        sb.AppendLine("    <StartupObject>Kassyi.GSharp.Tests.Shared.Differential.FuzzBatchCases</StartupObject>");
        if (isCuda && !string.IsNullOrWhiteSpace(cudaArch))
        {
            sb.AppendLine($"    <GSharpTargetArchitectures>{cudaArch}</GSharpTargetArchitectures>");
        }

        sb.AppendLine("  </PropertyGroup>");
        sb.AppendLine();
        sb.AppendLine("  <ItemGroup>");
        sb.AppendLine("    <CompilerVisibleProperty Include=\"GSharpTargetDialect\" />");
        sb.AppendLine("    <CompilerVisibleProperty Include=\"GSharpGenerateSnapshotTestCases\" />");
        sb.AppendLine($"    <Compile Include=\"{relGen}/FuzzBatchKernels.cu.cs\" />");
        sb.AppendLine($"    <Compile Include=\"{relGen}/FuzzBatchCases.cs\" />");
        sb.AppendLine($"    <Compile Include=\"{relGen}/FuzzBatchHarnessStubs.cs\" />");
        sb.AppendLine($"    <Compile Include=\"{relRepo}/tests/Compiler/Kassyi.GSharp.Tests.Shared/Differential/Harness/*.cs\" Exclude=\"{relRepo}/tests/Compiler/Kassyi.GSharp.Tests.Shared/Differential/Harness/KnownDivergences.cs\" />");
        if (!isCuda)
        {
            sb.AppendLine($"    <Compile Include=\"{relRepo}/tests/Compiler/Kassyi.GSharp.Tests.Shared/Helpers/ManagedKernelRun.cs\" />");
            sb.AppendLine("    <Using Include=\"Kassyi.GSharp.Tests.Shared.Helpers\" />");
        }

        sb.AppendLine("  </ItemGroup>");
        sb.AppendLine();
        sb.AppendLine("  <ItemGroup>");
        sb.AppendLine("    <PackageReference Include=\"xunit.assert\" Version=\"2.9.3\" />");
        sb.AppendLine("  </ItemGroup>");
        sb.AppendLine();
        sb.AppendLine("  <ItemGroup>");
        sb.AppendLine($"    <ProjectReference Include=\"{relRepo}/src/Core/Kassyi.GSharp.Core/Kassyi.GSharp.Core.csproj\" />");
        sb.AppendLine($"    <ProjectReference Include=\"{relRepo}/src/Runtime/Kassyi.GSharp.Runtime/Kassyi.GSharp.Runtime.csproj\" />");
        sb.AppendLine($"    <ProjectReference Include=\"{relRepo}/src/Compiler/Kassyi.GSharp.Compiler/Kassyi.GSharp.Compiler.csproj\" OutputItemType=\"Analyzer\" ReferenceOutputAssembly=\"true\" />");
        sb.AppendLine($"    <ProjectReference Include=\"{relRepo}/src/Compiler/Kassyi.GSharp.Compiler.Tasks/Kassyi.GSharp.Compiler.Tasks.csproj\" ReferenceOutputAssembly=\"false\" />");
        sb.AppendLine("  </ItemGroup>");
        sb.AppendLine();
        sb.AppendLine("  <UsingTask TaskName=\"Kassyi.GSharp.Compiler.Tasks.CompileCudaToFatbinTask\" AssemblyFile=\"$(GSharpCompilerTaskAssembly)\" />");
        sb.AppendLine("  <UsingTask TaskName=\"Kassyi.GSharp.Compiler.Tasks.CompileCppToNativeTask\" AssemblyFile=\"$(GSharpCompilerTaskAssembly)\" />");
        sb.AppendLine($"  <Import Project=\"{relRepo}/src/Compiler/Kassyi.GSharp.Compiler/build/Kassyi.GSharp.Compiler.targets\" />");
        sb.AppendLine("</Project>");
        return sb.ToString();
    }

    private static string NormalizeSlashes(string path) => path.Replace('\\', '/');

    private static void WriteIfChanged(string path, string content)
    {
        if (File.Exists(path))
        {
            string existing = File.ReadAllText(path, s_utf8NoBom);
            if (string.Equals(existing, content, StringComparison.Ordinal))
            {
                return;
            }
        }

        File.WriteAllText(path, content, s_utf8NoBom);
    }
}
