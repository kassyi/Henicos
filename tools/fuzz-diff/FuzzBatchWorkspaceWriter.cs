using System.Text;

namespace Kassyi.GSharp.Tools.FuzzDiff;

/// <summary>
/// Writes the generated batch source files and standalone temporary project scaffolds (<c>FuzzBatch.Cpu.csproj</c> and <c>FuzzBatch.Cuda.csproj</c>).
/// </summary>
public static class FuzzBatchWorkspaceWriter
{
    private static readonly UTF8Encoding s_utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

    /// <summary>
    /// Writes <c>FuzzBatchKernels.cu.cs</c>, <c>FuzzBatchCases.cs</c>, and (when <paramref name="repoRoot"/> is supplied)
    /// the standalone temporary project files in the parent workspace directory.
    /// </summary>
    public static void WriteBatch(GeneratedBatch batch, string outDir, string? repoRoot = null, string? cudaArch = null)
    {
        ArgumentNullException.ThrowIfNull(batch);
        ArgumentException.ThrowIfNullOrWhiteSpace(outDir);

        string fullOutDir = Path.GetFullPath(outDir);
        Directory.CreateDirectory(fullOutDir);

        string kernelsPath = Path.Combine(fullOutDir, "FuzzBatchKernels.cu.cs");
        string casesPath = Path.Combine(fullOutDir, "FuzzBatchCases.cs");

        File.WriteAllText(kernelsPath, batch.KernelsSource, s_utf8NoBom);
        File.WriteAllText(casesPath, batch.CasesSource, s_utf8NoBom);

        if (!string.IsNullOrWhiteSpace(repoRoot))
        {
            string workDir = Path.GetFileName(fullOutDir).Equals("Generated", StringComparison.OrdinalIgnoreCase)
                ? (Path.GetDirectoryName(fullOutDir) ?? fullOutDir)
                : fullOutDir;
            WriteProjectScaffolds(workDir, fullOutDir, Path.GetFullPath(repoRoot), cudaArch);
        }
    }

    /// <summary>
    /// Writes <c>Directory.Build.props</c>, <c>FuzzBatchHarnessStubs.cs</c>, <c>FuzzBatch.Cpu.csproj</c>, and <c>FuzzBatch.Cuda.csproj</c>
    /// into <paramref name="workDir"/> if they do not exist or if their contents changed.
    /// </summary>
    public static void WriteProjectScaffolds(string workDir, string generatedDir, string repoRoot, string? cudaArch = null)
    {
        Directory.CreateDirectory(workDir);

        string propsPath = Path.Combine(workDir, "Directory.Build.props");
        WriteIfChanged(propsPath, BuildDirectoryBuildProps());

        string stubsPath = Path.Combine(generatedDir, "FuzzBatchHarnessStubs.cs");
        WriteIfChanged(stubsPath, BuildHarnessStubs());

        string relGen = NormalizeSlashes(Path.GetRelativePath(workDir, generatedDir));
        string relRepo = NormalizeSlashes(Path.GetRelativePath(workDir, repoRoot));

        string cpuProjPath = Path.Combine(workDir, "FuzzBatch.Cpu.csproj");
        WriteIfChanged(cpuProjPath, BuildProjectXml(dialect: "Cpu", relGen, relRepo, cudaArch: null));

        string cudaProjPath = Path.Combine(workDir, "FuzzBatch.Cuda.csproj");
        WriteIfChanged(cudaProjPath, BuildProjectXml(dialect: "Cuda", relGen, relRepo, cudaArch));
    }

    internal static string BuildDirectoryBuildProps() =>
        """
        <Project>
          <!-- Isolated temporary fuzz batch build configuration: stops root analyzer/StyleCop inheritance. -->
          <PropertyGroup>
            <GSharpHostOs Condition="$([MSBuild]::IsOSPlatform('Windows'))">win</GSharpHostOs>
            <GSharpHostOs Condition="'$(GSharpHostOs)' == '' and $([MSBuild]::IsOSPlatform('Linux'))">linux</GSharpHostOs>
            <GSharpHostOs Condition="'$(GSharpHostOs)' == '' and $([MSBuild]::IsOSPlatform('OSX'))">osx</GSharpHostOs>
            <GSharpHostOs Condition="'$(GSharpHostOs)' == ''">unix</GSharpHostOs>

            <BaseOutputPath>bin\$(GSharpHostOs)\$(MSBuildProjectName)\</BaseOutputPath>
            <BaseIntermediateOutputPath>obj\$(GSharpHostOs)\$(MSBuildProjectName)\</BaseIntermediateOutputPath>
            <DefaultItemExcludes>$(DefaultItemExcludes);bin\**;obj\**;findings\**</DefaultItemExcludes>

            <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
            <GenerateDocumentationFile>false</GenerateDocumentationFile>
            <GSharpExportDeviceCode>false</GSharpExportDeviceCode>
            <GSharpGenerateSnapshotTestCases>false</GSharpGenerateSnapshotTestCases>
            <NoWarn>$(NoWarn);GS0001;GS0002;CS0162;CS0169;CS0219;CS1591;CS1717;CS1718;CS8019;CS8321;SA1600</NoWarn>
          </PropertyGroup>
        </Project>
        """;

    private static string BuildHarnessStubs() =>
        """
        // <auto-generated />
        #nullable enable
        global using System.Linq;
        global using Kassyi.GSharp.Runtime.Aot;
        global using Xunit;
        using System;

        namespace Xunit
        {
        [AttributeUsage(AttributeTargets.Method, AllowMultiple = false)]
        internal sealed class FactAttribute : Attribute
        {
        }
        [AttributeUsage(AttributeTargets.Method, AllowMultiple = false)]
        internal sealed class TheoryAttribute : Attribute
        {
        }
        }

        namespace Kassyi.GSharp.Compiler.Marshaling
        {
        internal static class AotHostNames
        {
        public static string ToSafeIdentifier(string name) => string.Create(name.Length, name, static (span, src) => { for (int i = 0; i < src.Length; i++) span[i] = src[i] == '.' ? '_' : src[i]; });
        }
        }

        namespace Kassyi.GSharp.Tests.Shared.Differential
        {
        public static class KnownDivergences
        {
        public static System.Collections.Generic.IReadOnlyList<KnownDivergence> All { get; } = [];
        }
        internal static class CudaCapability
        {
        public static void EnsureGpuAvailable()
        {
        if (!GpuKernelLoader.IsDriverAvailable)
        {
        throw new System.InvalidOperationException("NVIDIA GPU and CUDA Driver are required to run CUDA differential fuzz batches.");
        }
        }
        }
        }
        """;

    private static string BuildProjectXml(string dialect, string relGen, string relRepo, string? cudaArch)
    {
        bool isCuda = string.Equals(dialect, "Cuda", StringComparison.OrdinalIgnoreCase);
        string defineConstant = isCuda ? "GSHARP_CUDA" : "GSHARP_CPU";
        string cudaArchLine = isCuda && !string.IsNullOrWhiteSpace(cudaArch)
            ? $"\n    <GSharpTargetArchitectures>{cudaArch}</GSharpTargetArchitectures>"
            : string.Empty;
        string cpuCompileItems = !isCuda
            ? $"""

                <Compile Include="{relRepo}/tests/Compiler/Kassyi.GSharp.Tests.Shared/Helpers/ManagedKernelRun.cs" />
                <Using Include="Kassyi.GSharp.Tests.Shared.Helpers" />
            """
            : string.Empty;

        return $$"""
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <OutputType>Exe</OutputType>
                <TargetFramework>net10.0</TargetFramework>
                <ImplicitUsings>enable</ImplicitUsings>
                <Nullable>enable</Nullable>
                <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
                <GSharpTargetDialect>{{dialect}}</GSharpTargetDialect>
                <GSharpExportDeviceCode>false</GSharpExportDeviceCode>
                <GSharpGenerateSnapshotTestCases>false</GSharpGenerateSnapshotTestCases>
                <GSharpCompilerTaskAssembly>$(MSBuildThisFileDirectory){{relRepo}}/src/Compiler/Kassyi.GSharp.Compiler.Tasks/bin/$(GSharpHostOs)/$(Configuration)/netstandard2.0/Kassyi.GSharp.Compiler.Tasks.dll</GSharpCompilerTaskAssembly>
                <DefineConstants>$(DefineConstants);{{defineConstant}}</DefineConstants>
                <StartupObject>Kassyi.GSharp.Tests.Shared.Differential.FuzzBatchCases</StartupObject>{{cudaArchLine}}
              </PropertyGroup>

              <ItemGroup>
                <CompilerVisibleProperty Include="GSharpTargetDialect" />
                <CompilerVisibleProperty Include="GSharpGenerateSnapshotTestCases" />
                <Compile Include="{{relGen}}/FuzzBatchKernels.cu.cs" />
                <Compile Include="{{relGen}}/FuzzBatchCases.cs" />
                <Compile Include="{{relGen}}/FuzzBatchHarnessStubs.cs" />
                <Compile Include="{{relRepo}}/tests/Compiler/Kassyi.GSharp.Tests.Shared/Differential/Harness/*.cs" Exclude="{{relRepo}}/tests/Compiler/Kassyi.GSharp.Tests.Shared/Differential/Harness/KnownDivergences.cs" />{{cpuCompileItems}}
              </ItemGroup>

              <ItemGroup>
                <PackageReference Include="xunit.assert" Version="2.9.3" />
              </ItemGroup>

              <ItemGroup>
                <ProjectReference Include="{{relRepo}}/src/Core/Kassyi.GSharp.Core/Kassyi.GSharp.Core.csproj" />
                <ProjectReference Include="{{relRepo}}/src/Runtime/Kassyi.GSharp.Runtime/Kassyi.GSharp.Runtime.csproj" />
                <ProjectReference Include="{{relRepo}}/src/Compiler/Kassyi.GSharp.Compiler/Kassyi.GSharp.Compiler.csproj" OutputItemType="Analyzer" ReferenceOutputAssembly="true" />
                <ProjectReference Include="{{relRepo}}/src/Compiler/Kassyi.GSharp.Compiler.Tasks/Kassyi.GSharp.Compiler.Tasks.csproj" ReferenceOutputAssembly="false" />
              </ItemGroup>

              <UsingTask TaskName="Kassyi.GSharp.Compiler.Tasks.CompileCudaToFatbinTask" AssemblyFile="$(GSharpCompilerTaskAssembly)" />
              <UsingTask TaskName="Kassyi.GSharp.Compiler.Tasks.CompileCppToNativeTask" AssemblyFile="$(GSharpCompilerTaskAssembly)" />
              <Import Project="{{relRepo}}/src/Compiler/Kassyi.GSharp.Compiler/build/Kassyi.GSharp.Compiler.targets" />
            </Project>
            """;
    }

    internal static string NormalizeSlashes(string path) =>
        string.Create(path.Length, path, static (span, src) =>
        {
            for (int i = 0; i < src.Length; i++)
            {
                char c = src[i];
                span[i] = c == '\\' ? '/' : c;
            }
        });

    private static void WriteIfChanged(string path, string content)
    {
        if (File.Exists(path))
        {
            string existing = File.ReadAllText(path, s_utf8NoBom);
            if (string.Equals(existing, content, StringComparison.Ordinal))
            {
                return;
            }
        }

        File.WriteAllText(path, content, s_utf8NoBom);
    }
}
