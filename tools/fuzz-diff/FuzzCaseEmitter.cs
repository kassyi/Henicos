using System.Globalization;

namespace Kassyi.GSharp.Tools.FuzzDiff;

/// <summary>
/// Shared emitter for kernel/cases compilation-unit headers and <c>DifferentialCase</c> property definitions
/// used across <see cref="ScalarFuzzGenerator"/>, <see cref="FuzzSpeculativeBatchBuilder"/>, and <see cref="FuzzPromoter"/>.
/// </summary>
internal static class FuzzCaseEmitter
{
    /// <summary>
    /// Appends the standard kernel compilation-unit header (<c>#nullable enable</c>, warning suppressions, usings, and file-scoped namespace).
    /// </summary>
    internal static void AppendKernelsFileHeader(SourceWriter writer, string namespaceName, string? leadingComment = null)
    {
        if (!string.IsNullOrEmpty(leadingComment))
        {
            writer.AppendLine(leadingComment);
        }

        writer.AppendLine(
            $$"""
            #nullable enable
            #pragma warning disable CS0162, CS0219, CS1717, CS1718
            using System;
            using Kassyi.GSharp.Core;

            namespace {{namespaceName}};
            """);
        writer.AppendLine();
    }

    /// <summary>
    /// Appends the standard cases compilation-unit header (<c>// &lt;auto-generated /&gt;</c>, usings, and file-scoped namespace).
    /// </summary>
    internal static void AppendCasesFileHeader(SourceWriter writer, string namespaceName)
    {
        writer.AppendLine(
            $$"""
            // <auto-generated />
            // ReSharper disable All
            #nullable enable
            using System;
            using System.Collections.Generic;
            using System.Globalization;
            using System.Linq;
            using System.Text.Json;
            using Kassyi.GSharp.Core;

            namespace {{namespaceName}};
            """);
        writer.AppendLine();
    }

    /// <summary>
    /// Renders a single left-aligned <c>DifferentialCase</c> property declaration using an interpolated raw string literal.
    /// </summary>
    internal static string RenderDifferentialCaseProperty(
        string kernelClassName,
        string kernelMethodName,
        int? inputSeed,
        string headerComment,
        string column = "hash",
        string? oracleMethodName = null)
    {
        string effectiveOracleName = oracleMethodName ?? kernelMethodName;
        string seedsLine = inputSeed is { } s
            ? string.Create(CultureInfo.InvariantCulture, $"\nSeeds = [{s}],")
            : string.Empty;

        return $$"""
            {{headerComment}}
            public static DifferentialCase {{kernelMethodName}}_Case { get; } = new("{{kernelClassName}}.{{kernelMethodName}}")
            {
            Shape = LaunchShapes.PartialWarp(),{{seedsLine}}
            Inputs = static (rng, shape) =>
            {
            int rows = shape.Rows;
            var (inA, inB) = DiffValues.Int32Pairs(rng, rows);
            var inC = DiffValues.Values(rng, rows, DiffValues.ShiftCounts, DiffValues.NextInt32);
            return new DiffBuffers()
            .In("inA", inA)
            .In("inB", inB)
            .In("inC", inC)
            .Out<ulong>("checksum", rows, ["{{column}}"], OutputPolicy.Exact);
            },
            Launch = static (b, s) => {{kernelClassName}}.Launch{{kernelMethodName}}(b.Get<int>("inA"), b.Get<int>("inB"), b.Get<int>("inC"), b.Get<ulong>("checksum"), gridDimX: s.GridX, blockDimX: s.BlockX),
            Oracle = static (b, _) => {{kernelClassName}}.{{effectiveOracleName}}(b.Get<int>("inA"), b.Get<int>("inB"), b.Get<int>("inC"), b.Get<ulong>("checksum")),
            };
            """;
    }

    /// <summary>
    /// Builds the complete <c>FuzzBatchCases.cs</c> compilation unit for a batch of generated or speculative kernels.
    /// </summary>
    internal static string BuildCasesCompilationUnit(
        string namespaceName,
        string casesClassName,
        ulong batchFuzzSeed,
        IReadOnlyList<(string KernelName, ulong KernelSeed, string CasePropertySource)> entries,
        bool emitProgramMain)
    {
        using var writer = new SourceWriter();
        AppendCasesFileHeader(writer, namespaceName);

        using (writer.Scope($"public static class {casesClassName}"))
        {
            writer.AppendLine(string.Create(CultureInfo.InvariantCulture, $"public const ulong BatchFuzzSeed = {batchFuzzSeed}UL;"));
            writer.AppendLine();

            for (int i = 0; i < entries.Count; i++)
            {
                writer.AppendLine(entries[i].CasePropertySource);
                writer.AppendLine();
            }

            writer.AppendLine("public static IReadOnlyList<(string KernelName, ulong KernelSeed, DifferentialCase Case)> All { get; } =");
            writer.AppendLine("[");
            foreach (var entry in entries)
            {
                writer.AppendLine(string.Create(CultureInfo.InvariantCulture, $"(\"{entry.KernelName}\", {entry.KernelSeed}UL, {entry.KernelName}_Case),"));
            }

            writer.AppendLine("];");

            if (emitProgramMain)
            {
                writer.AppendLine();
                FuzzChecksumEmitter.AppendBatchRunnerMain(writer);
            }
        }

        return writer.ToString();
    }
}
